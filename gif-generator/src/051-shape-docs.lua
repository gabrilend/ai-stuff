-- 051-shape-docs.lua — writes docs/shape-format.md from the word lists,
-- or checks that it is up to date.
--
-- What this is, generally: the 3D vocabulary's documentation is printed
-- from the same lists the wall checks scenes against
-- (048-shape-words.lua), so a word cannot be legal and undocumented, or
-- documented and refused. The names the runtime owns (hues, shapes,
-- motion kinds, effects, solids) are listed from the modules themselves.
--
-- Usage: luajit src/051-shape-docs.lua DIR [--check]
--   (no flag)  write docs/shape-format.md
--   --check    write nothing; exit 1 if docs/shape-format.md differs from
--              what the lists give (the tests call this)

local DIR = "/mnt/mtwo/programming/ai-stuff/gif-generator"
local CHECK = false
for _, a in ipairs(arg or {}) do
    if a == "--check" then CHECK = true else DIR = a end
end

local meshes = dofile(DIR .. "/src/034-meshes.lua")
local choreography = dofile(DIR .. "/src/035-choreography.lua")
local words = dofile(DIR .. "/src/048-shape-words.lua")
local TARGET = DIR .. "/docs/shape-format.md"

-- The hues every film hands in (039-shape-films.lua): the house seven and
-- white light.
local HUE_NOTE = "`rose ember gold jade teal ice violet`, the gif generator's hue "
    .. "vocabulary, and `cloud`, white light"

-- {{{ local function kind_text()
-- What a word takes, said for a reader.
local KIND_TEXT = {
    value = "a value", tag = "a tag", ref = "a tag carried elsewhere", refs = "a list of tags carried elsewhere",
    hue = "a hue", hues = "a list of hues", mesh = "a shape", mesh_params = "the shape's proportions",
    style = "a style", shards = "`own` or `rainbow`", effect = "an effect", solids = "a list of solids",
    motion = "a motion", camera_motion = "a camera motion", route_point = "a point or an anchor",
    route_points = "a list of points or anchors", target = "a point or `\"ahead\"`",
    roll_or_false = "a roll, or `false`",
}
local function kind_text(kind)
    if type(kind) == "table" then return "a list of " .. kind.list .. " tables" end
    return KIND_TEXT[kind] or ("a " .. kind .. " table")
end
-- }}}

-- {{{ local function table_of()
-- One context's words as a markdown table.
local function table_of(list, out)
    if #list == 0 then
        out[#out + 1] = "Takes no words."
        out[#out + 1] = ""
        return
    end
    out[#out + 1] = "| Word | Takes | Meaning |"
    out[#out + 1] = "|------|-------|---------|"
    for _, entry in ipairs(list) do
        out[#out + 1] = string.format("| `%s` | %s | %s |", entry[1], kind_text(entry[2]), entry[3])
    end
    out[#out + 1] = ""
end
-- }}}

-- {{{ local function sorted_keys()
local function sorted_keys(tbl)
    local list = {}
    for k in pairs(tbl) do list[#list + 1] = k end
    table.sort(list)
    return list
end
-- }}}

-- {{{ local function document()
local function document()
    local owned = choreography.vocabulary()
    local out = {
        "# Shape scene format",
        "",
        "Generated by `src/051-shape-docs.lua` from `src/048-shape-words.lua`, the same lists",
        "the wall (`src/049-shape-wall.lua`) checks every scene against. Edit those, then run",
        "`luajit src/051-shape-docs.lua .`; never edit this file by hand.",
        "",
        "A scene is data: a Lua file returning one table, read in an empty sandbox. A word not",
        "listed for the place it stands is refused, with every other mistake in the scene, each",
        "with the nearest legal word.",
        "",
        "## World space",
        "",
        table.concat(words.WORLD_SPACE, "\n"),
        "",
        "## Names",
        "",
        "- Hues: " .. HUE_NOTE .. ".",
        "- Shapes: " .. "`" .. table.concat(meshes.names(), "` `") .. "`.",
        "- Styles: `" .. table.concat(words.STYLES, "` `") .. "`.",
        "- Effects: `" .. table.concat(owned.effects, "` `") .. "`.",
        "- Solids a superball morphs through: `" .. table.concat(owned.solids, "` `") .. "`.",
        "- Route motions (the ones a rolling, becoming or anchored shape needs): `"
            .. table.concat(owned.routes, "` `") .. "`.",
        "- Tags made without being written: `" .. table.concat(words.MADE_TAGS, "` `") .. "`.",
        "",
        "## Places",
        "",
    }
    for _, name in ipairs(words.ORDER) do
        out[#out + 1] = "### `" .. name .. "`"
        out[#out + 1] = ""
        table_of(words.CONTEXTS[name], out)
    end

    out[#out + 1] = "## Shape motions"
    out[#out + 1] = ""
    out[#out + 1] = "Every motion takes `kind`, the words of its kind, and these:"
    out[#out + 1] = ""
    table_of(words.MOTION_COMMON, out)
    for _, kind in ipairs(sorted_keys(words.MOTIONS)) do
        out[#out + 1] = "### `" .. kind .. "`"
        out[#out + 1] = ""
        table_of(words.MOTIONS[kind], out)
    end

    out[#out + 1] = "## Camera motions"
    out[#out + 1] = ""
    out[#out + 1] = "Every camera motion takes `kind` and the words of its kind."
    out[#out + 1] = ""
    for _, kind in ipairs(sorted_keys(words.CAMERA_MOTIONS)) do
        out[#out + 1] = "### `" .. kind .. "`"
        out[#out + 1] = ""
        table_of(words.CAMERA_MOTIONS[kind], out)
    end

    out[#out + 1] = "## Shape proportions"
    out[#out + 1] = ""
    out[#out + 1] = "A shape's `mesh_params`, by shape. A scene's `ground` takes the terrain's."
    out[#out + 1] = ""
    for _, mesh in ipairs(meshes.names()) do
        out[#out + 1] = "### `" .. mesh .. "`"
        out[#out + 1] = ""
        table_of(words.MESH_PARAMS[mesh], out)
    end
    return table.concat(out, "\n")
end
-- }}}

local text = document()
local handle = io.open(TARGET, "rb")
local current = handle and handle:read("*a")
if handle then handle:close() end

if CHECK then
    if current ~= text then
        print("shape-docs: docs/shape-format.md " .. (current and "differs from" or "is missing;")
              .. " what the word lists give; run luajit src/051-shape-docs.lua DIR")
        os.exit(1)
    end
    print("shape-docs: docs/shape-format.md matches the word lists")
elseif current ~= text then
    handle = assert(io.open(TARGET, "wb"))
    handle:write(text)
    handle:close()
    print("shape-docs: wrote docs/shape-format.md")
end
