-- 046-make-shapes.lua — writes each generated shape scene from its
-- generator, or checks that every generated scene is up to date.
--
-- What this is, generally: a scene that needs to compute lives as a
-- generator, an ordinary Lua program in input/shapes/generators/ that
-- returns a scene table. This runs each one and writes what it returns,
-- as plain data, to input/shapes/<name>.lua, where the films read it in
-- a sandbox (045-scene-file.lua). The generator's opening comment is
-- carried over, under a line saying where the scene came from, so the
-- scene still reads as its own description.
--
-- Usage: luajit src/046-make-shapes.lua DIR [--check]
--   (no flag)  write every generated scene
--   --check    write nothing; report every generated scene that is
--              missing or differs from what its generator gives, exit 1
--              if any does (the tests call this)

local DIR = "/mnt/mtwo/programming/ai-stuff/gif-generator"
local CHECK = false
for _, a in ipairs(arg or {}) do
    if a == "--check" then CHECK = true else DIR = a end
end

local scene_file = dofile(DIR .. "/src/045-scene-file.lua")
local SHAPES = DIR .. "/input/shapes"
local GENERATORS = SHAPES .. "/generators"
local MARK = "-- generated by make-shapes from generators/"

-- {{{ local function generator_names()
-- Every generator, by bare name. Folders inside (parts/) are not
-- generators; they hold what generators share.
local function generator_names()
    local names = {}
    local listing = io.popen(string.format("ls -1 %q", GENERATORS))
    for line in listing:lines() do
        local name = line:match("^(.+)%.lua$")
        if name then names[#names + 1] = name end
    end
    listing:close()
    return names
end
-- }}}

-- {{{ local function read_text()
local function read_text(path)
    local handle = io.open(path, "rb")
    if not handle then return nil end
    local text = handle:read("*a")
    handle:close()
    return text
end
-- }}}

-- {{{ local function opening_comment()
-- The generator's first comment block, as written: the scene's own words
-- about itself.
local function opening_comment(source)
    local lines = {}
    for line in (source .. "\n"):gmatch("([^\n]*)\n") do
        if line:match("^%-%-") then lines[#lines + 1] = line else break end
    end
    return table.concat(lines, "\n")
end
-- }}}

-- {{{ local function generate()
-- One generator run; returns the plain scene's text.
local function generate(name)
    local path = GENERATORS .. "/" .. name .. ".lua"
    local scene = dofile(path)
    local header = MARK .. name .. ".lua; edit that, then run ./make-shapes"
    local comment = opening_comment(read_text(path) or "")
    if comment ~= "" then header = header .. "\n--\n" .. comment end
    return scene_file.write(scene, header)
end
-- }}}

local problems = 0
local names = generator_names()
for _, name in ipairs(names) do
    local target = SHAPES .. "/" .. name .. ".lua"
    local current = read_text(target)
    local ok, text = pcall(generate, name)
    -- Four paths: the generator fails (said, counted); a hand-written scene
    -- holds the name (never overwritten); checking (stale or missing is a
    -- problem); writing (the file is written).
    if not ok then
        print("make-shapes: " .. name .. ": the generator failed: " .. tostring(text))
        problems = problems + 1
    elseif current and current:sub(1, #MARK) ~= MARK then
        print("make-shapes: " .. name .. ": input/shapes/" .. name
              .. ".lua is written by hand; a generator may not replace it")
        problems = problems + 1
    elseif CHECK then
        if current ~= text then
            print("make-shapes: " .. name .. ": input/shapes/" .. name .. ".lua "
                  .. (current and "differs from" or "is missing; run ./make-shapes for")
                  .. " what its generator gives")
            problems = problems + 1
        end
    elseif current ~= text then
        local handle = assert(io.open(target, "wb"))
        handle:write(text)
        handle:close()
        print("make-shapes: wrote input/shapes/" .. name .. ".lua")
    end
end

if CHECK and problems == 0 then
    print(string.format("make-shapes: all %d generated scenes match their generators", #names))
end
if problems > 0 then os.exit(1) end
