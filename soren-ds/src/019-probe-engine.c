/* MMIO accessors. */
static inline uint32_t mmio_r32(uint32_t a) { return *(volatile uint32_t *)(uintptr_t)a; }
static inline uint16_t mmio_r16(uint32_t a) { return *(volatile uint16_t *)(uintptr_t)a; }
