/* {{{ otp_probe — bring the OTP (eFuse) controller up enough to read it
 * Base 0xFE38C000 (non-secure OTP — the one that exposes the chip ID from a
 * non-secure EL). A read while the OTP bus clock is gated STALLS the APB
 * bridge and hangs the CPU, so ungate + release reset FIRST:
 *   CLKGATE_CON(26) @0xFDD20368 bits 9/10/11 (PCLK/SBPI/USR) -> ungate 0x0E000000
 *   SOFTRST_CON(22) @0xFDD20458 bit 12 (SRST_P_OTPC_NS)      -> release 0x10000000
 * then read OTPC_INT_STATUS @+0x0304 as a presence/clocking check.
 *
 * CONFIRMED against the TRM (extracted with ghostscript txtwrite): base
 * 0xFE38C000 = OTP_NS (Part1 Table 1-1); clock gates CLKGATE_CON26 bits 9/10/11
 * (pclk/sbpi/usr_otpc_ns) and reset SOFTRST_CON22 bit 12 (presetn_otpc_ns)
 * (Part1 Ch2). The OTP *controller* register map — the chip-ID FSM (USER_CTRL /
 * USER_ADDR=word 0xa / USER_ENABLE -> poll INT_STATUS -> read USER_Q@+0x124) —
 * is NOT in the public TRM (there is no OTP-controller chapter). The FSM and
 * every bit value ARE documented in docs/driver-refs/rockchip-otp.c
 * (rk3568_otp_read): user mode via USER_CTRL=0x00010001, per-word USER_ADDR=
 * offset|0xFFFF0000 + USER_ENABLE=0x00010001, poll INT_STATUS bit2 (USER_DONE),
 * read USER_Q; cpuid = 16 bytes ~word offset 0xa; needs an SBPI reset + ECC
 * preamble first. otp_read_cpuid() below implements that FSM (ported from the
 * driver); this probe does the presence read and then calls it. */
static void otp_probe(void)
{
    debug_write("[otp] ungate CON26 b9-11 + release CON22 b12\r\n");
    mmio_w32(0xFDD20368u, 0x0E000000u);
    mmio_w32(0xFDD20458u, 0x10000000u);
    busy_delay(10000u);
    debug_write("[otp] OTPC_INT_STATUS @0xFE38C304 = ");
    write_hex32(mmio_r32(0xFE38C304u));
    debug_write("\r\n");
    otp_read_cpuid();
}
/* }}} */

/* {{{ rng_probe — draw from the hardware RNG (inside the crypto complex)
 * Base 0xFE388000. A read while HCLK_CRYPTO_NS is gated hangs the AHB, so
 * ungate + release reset FIRST:
 *   CLKGATE_CON(8) @0xFDD20320 bit 12 (HCLK) + bit 15 (RNG) -> ungate 0x90000000
 *   SOFTRST_CON(6) @0xFDD20418 bit 8 (H_CRYPTO) + bit 11 (RNG) -> release 0x09000000
 * then start a draw via TRNG_RNG_CTL @+0x0400 and poll until its START bit
 * self-clears (that clear IS "data ready"), then read the eight output words
 * at +0x0410..+0x042C. The poll is BOUNDED so a wrong CTL value can only time
 * out, never hang.
 *
 * CONFIRMED against the TRM (extracted with ghostscript txtwrite): base
 * 0xFE388000 = TRNG_NS (Part1 Table 1-1); clock gates CLKGATE_CON8 bit 12
 * (hclk_crypto_ns) + bit 15 (clk_crypto_ns_rng) and reset SOFTRST_CON6 (Part1
 * Ch2); and the RNG_CTL start sequence + DOUT register offsets (Part2 Ch5). */
static void rng_probe(void)
{
    debug_write("[rng] ungate CON8 b12/15 + release CON6 b8/11\r\n");
    mmio_w32(0xFDD20320u, 0x90000000u);
    mmio_w32(0xFDD20418u, 0x09000000u);
    busy_delay(10000u);

    /* TRNG start sequence, CONFIRMED against TRM Part 2 Ch5. RNG_CTL (+0x400)
     * uses the upper-16-bit write-enable mask (bits 31:16 select which of
     * 15:0 change). The TRM's order: set rng_enable (bit1) FIRST, then set
     * rng_start (bit0) on its own — rng_start self-clears to 0 when the draw
     * is done. ring_sel (bits 3:2) defaults to fastest (RNG_CTL reset 0x0C)
     * and a masked write leaves it untouched. */
    mmio_w32(0xFE388404u, 0x00000000u);   /* RNG_SAMPLE_CNT = default rate    */
    mmio_w32(0xFE388400u, 0x00020002u);   /* rng_enable = 1 (mask+value bit1) */
    mmio_w32(0xFE388400u, 0x00010001u);   /* rng_start  = 1 (mask+value bit0) */
    int ready = 0;
    for (int i = 0; i < 200000; i++) {
        if ((mmio_r32(0xFE388400u) & 0x1u) == 0u) { ready = 1; break; }
    }
    debug_write(ready ? "[rng] rng_start self-cleared -> data ready\r\n"
                      : "[rng] TIMEOUT (rng_start never cleared)\r\n");
    if (ready) {
        debug_write("[rng] DOUT0-7:");
        for (uint32_t o = 0; o < 8u; o++) {
            debug_write(" ");
            write_hex32(mmio_r32(0xFE388410u + o * 4u));
        }
        debug_write("\r\n[rng] (words should differ run-to-run; all-equal/zero = stuck)\r\n");
    }
}
/* }}} */

/* {{{ crypto_probe — confirm the crypto accelerator is present and clocked
 * Base 0xFE380000. RK3568 crypto v2 exposes NO dedicated version/ID register,
 * so this is a presence/clocking check: ungate + release reset, then read the
 * first control register (CRYPTO_CLK_CTL @+0x0000). A read while ACLK/HCLK are
 * gated hangs the bus, so ungate FIRST:
 *   CLKGATE_CON(8) @0xFDD20320 bits 11-15 -> ungate 0xF8000000
 *   SOFTRST_CON(6) @0xFDD20418 bits 7-11  -> release 0x0F800000
 * CONFIRMED against the TRM (extracted with ghostscript txtwrite): base
 * 0xFE380000 = CRYPTO_NS (Part1 Table 1-1); CRYPTO_CLK_CTL @+0x0 reset 0x1
 * (Part2 Ch4); clock gates CLKGATE_CON8 bits 11/12 (aclk/hclk_crypto_ns)
 * (Part1 Ch2). A non-hanging read is the whole result — no version/ID reg. */
static void crypto_probe(void)
{
    debug_write("[crypto] ungate CON8 b11-15 + release CON6 b7-11\r\n");
    mmio_w32(0xFDD20320u, 0xF8000000u);
    mmio_w32(0xFDD20418u, 0x0F800000u);
    busy_delay(10000u);
    debug_write("[crypto] CRYPTO_CLK_CTL @0xFE380000 = ");
    write_hex32(mmio_r32(0xFE380000u));
    debug_write("\r\n[crypto] (CLK_CTL reset=0x1 per TRM Part2 Ch4; no version reg; non-hang = reachable)\r\n");
}
/* }}} */

/* {{{ timer_recon — read the ARM architected generic timer
 * Every core carries a counter (CNTPCT_EL0) that ticks at a fixed rate
 * (CNTFRQ_EL0), independent of the CPU clock — so it keeps real wall-clock
 * time even as the CPU clock changes. Reading the counter twice across a
 * fixed nop delay turns nop counts into measured time. It answers three
 * things at once: what rate firmware programmed the timer at (expected
 * ~24 MHz), how long our nop-counted busy_delay REALLY is (to calibrate
 * delay_busy), and it de-risks phase-2 scheduling, which leans on this
 * counter. System registers are read with MRS (not MMIO), so this is a C
 * CALL target rather than an R line. */
static void timer_recon(void)
{
    uint64_t freq = 0, t0 = 0, t1 = 0;
    __asm__ volatile ("mrs %0, cntfrq_el0" : "=r"(freq));
    __asm__ volatile ("mrs %0, cntpct_el0" : "=r"(t0));
    busy_delay(1000000u);
    __asm__ volatile ("mrs %0, cntpct_el0" : "=r"(t1));

    debug_write("[timer] CNTFRQ_EL0 (Hz) = ");
    write_hex32((uint32_t)freq);
    debug_write(" = ");
    write_dec((uint32_t)freq);
    debug_write("\r\n[timer] CNTPCT delta over ~1e6 nop loop = ");
    write_hex32((uint32_t)(t1 - t0));
    debug_write("\r\n");

    /* Elapsed microseconds = delta * 1e6 / freq, integer math (no FP in the
     * kernel). Tells us how long a million-nop busy_delay really is, so
     * delay_busy can be calibrated and dumps can report true MB/s. */
    if (freq != 0u) {
        uint32_t us = (uint32_t)(((t1 - t0) * 1000000u) / freq);
        debug_write("[timer] ~1e6 nop loop = ");
        write_dec(us);
        debug_write(" us of real time\r\n");
    }
}
/* }}} */

/* {{{ CALL dispatch — whole driver routines by name */
static void call_target(const char *name)
{
    if (streq(name, "timer_recon")) {
        timer_recon();
    } else if (streq(name, "cpu_recon")) {
        cpu_core_recon();
    } else if (streq(name, "emmc_wear")) {
        emmc_wear_report();
    } else if (streq(name, "memtest_full")) {
        memtest_full();
    } else if (streq(name, "otp_probe")) {
        otp_probe();
    } else if (streq(name, "rng_probe")) {
        rng_probe();
    } else if (streq(name, "crypto_probe")) {
        crypto_probe();
    } else if (streq(name, "gic_probe")) {
        gic_probe();
    } else if (streq(name, "i2c_scan")) {
        i2c0_scan();
    } else if (streq(name, "audio_recon")) {
        audio_codec_recon();
    } else if (streq(name, "sd_init")) {
        debug_write("[probe] CALL sd_init -> ");
        write_hex32((uint32_t)sd_init());
        debug_write("\r\n");
    } else if (streq(name, "emmc_init")) {
        debug_write("[probe] CALL emmc_init -> ");
        write_hex32((uint32_t)emmc_init());
        debug_write("\r\n");
    } else if (streq(name, "emmc_read0")) {
        /* Read eMMC block 0 and log its first word — a quick
         * "is the eMMC alive and returning real data" check. */
        static uint8_t blk[512];
        int r = emmc_read_block(0, blk);
        debug_write("[probe] CALL emmc_read0 -> ");
        write_hex32((uint32_t)r);
        if (r == 0) {
            debug_write(" word0=");
            write_hex32(((uint32_t)blk[0]) | ((uint32_t)blk[1] << 8)
                        | ((uint32_t)blk[2] << 16) | ((uint32_t)blk[3] << 24));
        }
        debug_write("\r\n");
    } else if (streq(name, "backup_boot")) {
        /* Copy just the eMMC's BOOTLOADER region — the Rockchip boot
         * chain (GPT at LBA 1, idbloader at LBA 64, u-boot at LBA 16384)
         * living in the 16 MB before the first partition — to the SD's
         * reserved region at LBA 0x200000. 32768 sectors = 16 MB. This is
         * the targeted safety copy (110e); when we install our own boot
         * image (110b), retarget this to wherever that lands. */
        debug_write("[probe] CALL backup_boot -> ");
        write_hex32((uint32_t)emmc_backup_to_sd(0, 0x200000u, 32768u));
        debug_write("\r\n");
    } else if (streq(name, "memtest")) {
        memtest_run();
    } else if (streq(name, "pmic_dump")) {
        pmic_dump();
    } else if (streq(name, "pmic_write_test")) {
        pmic_write_test();
    } else if (streq(name, "pmic_ldo_test")) {
        pmic_ldo_test();
    } else if (streq(name, "emmc_ext_csd")) {
        emmc_ext_csd_dump();
    } else if (streq(name, "emmc_hs200")) {
        /* Stage A of the fast-storage path (110j): switch the card to
         * HS200. A following CALL emmc_read0 is the go/no-go. */
        debug_write("[probe] CALL emmc_hs200 -> ");
        write_hex32((uint32_t)emmc_switch_hs200());
        debug_write("\r\n");
    } else if (streq(name, "emmc_hs400")) {
        /* Stage B (110j): transition HS200 -> HS400. Must follow a
         * successful emmc_hs200. A following emmc_read0 is the go/no-go. */
        debug_write("[probe] CALL emmc_hs400 -> ");
        write_hex32((uint32_t)emmc_switch_hs400());
        debug_write("\r\n");
    } else if (streq(name, "emmc_verify")) {
        /* Read a fixed non-zero block and log its fingerprint — run at
         * each speed to prove the fast read is byte-identical (110j). */
        emmc_verify();
    } else if (streq(name, "emmc_verify_dma")) {
        /* Read that block via ADMA2 (DMA) and fingerprint it — must match
         * the PIO fingerprint to prove the descriptor path is correct (110m). */
        emmc_verify_dma();
    } else if (streq(name, "emmc_dump")) {
        /* Sparse eMMC -> SD dump (110m) — packs only the non-zero chunks to
         * the SD and logs a MAP for reconstruct-emmc to rebuild from (110m). */
        debug_write("[probe] CALL emmc_dump -> ");
        write_hex32((uint32_t)emmc_dump_to_sd());
        debug_write("\r\n");
    } else if (streq(name, "emmc_scan")) {
        /* Scan the whole eMMC and log where the NON-ZERO data is (110m) —
         * a cheap layout map for a mostly-zero card, no big SD write. */
        debug_write("[probe] CALL emmc_scan -> ");
        write_hex32((uint32_t)emmc_scan_map());
        debug_write("\r\n");
    } else if (streq(name, "sd_caps")) {
        /* Read what the SD card supports (SCR / SD_STATUS / SWITCH_FUNC) —
         * the dynamic-probe foundation for the SD fast path (110l). */
        sd_probe_capabilities();
    } else if (streq(name, "sd_dma")) {
        /* Write a pattern to a reserved SD block via the IDMAC, read it
         * back PIO, and compare — proves the microSD DMA *write* engine,
         * the direction the eMMC dump needs (110m). */
        sd_dma_write_test();
    } else if (streq(name, "sd_speed")) {
        /* Dynamically pick the safe SD bus speed (the minimum of the card
         * and host ceilings) and apply it, logging the decision (110l). */
        sd_select_speed();
    } else {
        debug_write("[probe] CALL unknown target: ");
        debug_write(name);
        debug_write("\r\n");
    }
}
/* }}} */

/* {{{ execute one script line */
static void run_line(const char *line, int writes_enabled)
{
    const char *p = skip_ws(line);
    if (*p == 0 || *p == '#') return;            /* blank or comment */

    char cmd[12];
    read_token(&p, cmd, sizeof cmd);

    int ok = 0;

    if (streq(cmd, "R") || streq(cmd, "RH") || streq(cmd, "RB")) {
        uint32_t addr = parse_hex(&p, &ok);
        if (!ok) { debug_write("[probe] R: bad address\r\n"); return; }
        uint32_t v = streq(cmd, "RH") ? mmio_r16(addr)
                   : streq(cmd, "RB") ? mmio_r8(addr)
                   : mmio_r32(addr);
        debug_write("[probe] ");
        debug_write(cmd);
        debug_write(" ");
        write_hex32(addr);
        debug_write(" = ");
        write_hex32(v);
        debug_write("\r\n");

    } else if (streq(cmd, "W") || streq(cmd, "WH") || streq(cmd, "WB")) {
        uint32_t addr = parse_hex(&p, &ok);
        if (!ok) { debug_write("[probe] W: bad address\r\n"); return; }
        uint32_t val = parse_hex(&p, &ok);
        if (!ok) { debug_write("[probe] W: bad value\r\n"); return; }
        if (!writes_enabled) {
            debug_write("[probe] W skipped (writes not enabled in header): ");
            write_hex32(addr); debug_write("\r\n");
            return;
        }
        if (!write_allowed(addr)) {
            debug_write("[probe] W BLOCKED (outside allowlist): ");
            write_hex32(addr); debug_write("\r\n");
            return;
        }
        if (streq(cmd, "WH")) mmio_w16(addr, (uint16_t)val);
        else if (streq(cmd, "WB")) mmio_w8(addr, (uint8_t)val);
        else mmio_w32(addr, val);
        debug_write("[probe] ");
        debug_write(cmd);
        debug_write(" ");
        write_hex32(addr);
        debug_write(" <= ");
        write_hex32(val);
        debug_write("\r\n");

    } else if (streq(cmd, "DUMP")) {
        uint32_t addr = parse_hex(&p, &ok);
        if (!ok) { debug_write("[probe] DUMP: bad address\r\n"); return; }
        uint32_t count = parse_dec(&p, &ok);
        if (!ok) count = 4;
        if (count > 64) count = 64;              /* keep the log sane */
        for (uint32_t i = 0; i < count; i++) {
            debug_write("[probe]   ");
            write_hex32(addr + i * 4u);
            debug_write(" = ");
            write_hex32(mmio_r32(addr + i * 4u));
            debug_write("\r\n");
        }

    } else if (streq(cmd, "DELAY")) {
        uint32_t n = parse_dec(&p, &ok);
        if (!ok) n = 100000;
        busy_delay(n);
        debug_write("[probe] DELAY done\r\n");

    } else if (streq(cmd, "EXPECT")) {
        uint32_t addr = parse_hex(&p, &ok);
        if (!ok) { debug_write("[probe] EXPECT: bad address\r\n"); return; }
        uint32_t want = parse_hex(&p, &ok);
        if (!ok) { debug_write("[probe] EXPECT: bad value\r\n"); return; }
        uint32_t mask = parse_hex(&p, &ok);
        if (!ok) mask = 0xFFFFFFFFu;
        uint32_t got = mmio_r32(addr) & mask;
        debug_write("[probe] EXPECT ");
        write_hex32(addr);
        debug_write(got == (want & mask) ? " PASS got=" : " FAIL got=");
        write_hex32(got);
        debug_write(" want=");
        write_hex32(want & mask);
        debug_write("\r\n");

    } else if (streq(cmd, "POLL")) {
        /* POLL <addr> <want> <mask> <maxtries> — read addr until
         * (value & mask) == (want & mask), or maxtries elapse.
         * The wait-for-a-ready-bit primitive: DLL lock, clock
         * stable, command-done, etc. Logs how many tries it took
         * or TIMEOUT with the last value seen. */
        uint32_t addr = parse_hex(&p, &ok);
        if (!ok) { debug_write("[probe] POLL: bad address\r\n"); return; }
        uint32_t want = parse_hex(&p, &ok);
        if (!ok) { debug_write("[probe] POLL: bad value\r\n"); return; }
        uint32_t mask = parse_hex(&p, &ok);
        if (!ok) mask = 0xFFFFFFFFu;
        uint32_t tries = parse_dec(&p, &ok);
        if (!ok) tries = 100000u;
        uint32_t i, got = 0;
        for (i = 0; i < tries; i++) {
            got = mmio_r32(addr) & mask;
            if (got == (want & mask)) break;
            busy_delay(64);
        }
        debug_write("[probe] POLL ");
        write_hex32(addr);
        if (got == (want & mask)) {
            debug_write(" MATCH after ");
            write_hex32(i);
            debug_write(" tries\r\n");
        } else {
            debug_write(" TIMEOUT got=");
            write_hex32(got);
            debug_write(" want=");
            write_hex32(want & mask);
            debug_write("\r\n");
        }

    } else if (streq(cmd, "CALL")) {
        char name[16];
        read_token(&p, name, sizeof name);
        call_target(name);

    } else if (streq(cmd, "LOG")) {
        /* Echo the rest of the line verbatim — a readable marker. */
        debug_write("[probe] LOG: ");
        debug_write(skip_ws(p));
        debug_write("\r\n");

    } else {
        debug_write("[probe] unknown command: ");
        debug_write(cmd);
        debug_write("\r\n");
    }
}
/* }}} */

/* {{{ run_probe_text — run one compiled-in probe through the interpreter
 * Brackets the run with banners carrying `name` so the log is
 * splittable per probe and a hang is pinned to the last START banner
 * with no END. The text is a .rodata literal, so it is copied into the
 * writable scratch buffer before each line is NUL-terminated in place. */
static void run_probe_text(const char *name, int writes_enabled, const char *text)
{
    debug_write("\r\n[probe] ===== PROBE ");
    debug_write(name);
    debug_write(writes_enabled ? " (writes) =====\r\n" : " =====\r\n");

    uint32_t len = 0;
    while (text[len] != 0 && len < PROBE_BUF_BYTES - 1u) {
        probe_buf[len] = (uint8_t)text[len];
        len++;
    }
    char *buf = (char *)probe_buf;
    buf[len] = 0;

    uint32_t start = 0;
    for (uint32_t i = 0; i <= len; i++) {
        if (buf[i] == '\n' || buf[i] == '\r' || buf[i] == 0) {
            char saved = buf[i];
            buf[i] = 0;
            run_line(buf + start, writes_enabled);
            buf[i] = saved;
            start = i + 1;
            if (saved == 0) break;
        }
    }

    debug_write("[probe] ===== END ");
    debug_write(name);
    debug_write(" =====\r\n");
}
/* }}} */

/* {{{ probe_seed_defaults — arm each probe per its compiled-in default
 * Copies each probe's #NEEDED bit (its default arm state) into the mutable
 * run-flag array. Called once at boot in a --debug build; a production
 * build never links this file. #NEEDED now defaults to 0 (opt-in, issue
 * 110n), so only probes that explicitly asked to run are armed here. */
void probe_seed_defaults(void)
{
    for (unsigned i = 0; i < builtin_probe_count; i++) {
        probe_runflags[i] = (uint8_t)(builtin_probes[i].needed ? 1u : 0u);
    }
}
/* }}} */

/* {{{ probe_arm — arm one probe by its generated index
 * Sets a probe's run-flag so the next run_probes() runs it. The runtime-
 * trigger entry point for callers outside the boot seed (a button combo, a
 * USB console). An out-of-range index is ignored rather than trusted. */
void probe_arm(enum probe_index which)
{
    if ((unsigned)which < builtin_probe_count) {
        probe_runflags[(unsigned)which] = 1u;
    }
}
/* }}} */

/* {{{ run_probes — run every armed probe in sweep order, then self-clear
 * Walks probe_runflags[] (sweep order, already sorted by #AUTO priority)
 * and runs each ARMED probe through the interpreter. After a probe runs,
 * its output is flushed to the SD-backed log — the always-present sink;
 * screen / audio / other sinks join here as they come up — and then its
 * flag is cleared, so a slot reads 0 once its results are safely written
 * and the probe re-runs only if re-armed. An unarmed slot logs a
 * DE-SELECTED banner in its place, so the roster stays honest: a skipped
 * probe reads as deliberately skipped, not missing.
 *
 * Callable from anywhere: arm a probe (probe_arm) and call this to run it
 * on demand — the runtime-trigger seam (issue 110n). The flush-after-each
 * also means a hang leaves everything before it safe on the card — the
 * stuck probe is the last START banner with no END. Supersedes 110i's
 * terminal probe_engine_run. */
void run_probes(void)
{
    debug_write("\r\n[probe] ########## RUN ARMED PROBES ##########\r\n");

    /* Drive the LEDs over PWM: the top window holds green ("running"), the
     * bottom amber is a bar that fills across the roster (position in the
     * list, not work done), and at the end the top flips to red ("done").
     * led_top/led_bottom live in 003-pwm.c. */
    led_pwm_init();
    led_top(0u, 1u, 1u, 1u);    /* red off, green full -> top green */

    /* Segment the bottom-LED bar by the probes ARMED THIS run, not by how
     * many probes exist — the developer cares about progress through *this*
     * run (probe 2 of 5 armed = 40%), not our total probe count. Count the
     * armed ones up front, then advance the bar as each one finishes. */
    uint32_t armed_total = 0;
    for (unsigned i = 0; i < builtin_probe_count; i++) {
        if (probe_runflags[i]) armed_total++;
    }

    uint32_t armed_done = 0;
    for (unsigned i = 0; i < builtin_probe_count; i++) {
        /* Unarmed / de-selected this run: keep it in the roster with a
         * banner so the log shows a deliberate skip, not a missing probe —
         * "de-selected" is more informative than "absent". It does NOT move
         * the bar, since it is not part of this run's work. */
        if (!probe_runflags[i]) {
            debug_write("\r\n[probe] ===== PROBE ");
            debug_write(builtin_probes[i].name);
            debug_write(" DE-SELECTED (not armed) =====\r\n");
            debug_log_flush();
            continue;
        }

        run_probe_text(builtin_probes[i].name,
                       builtin_probes[i].writes_enabled,
                       builtin_probes[i].text);
        debug_log_flush();          /* commit results before clearing */
        probe_runflags[i] = 0u;     /* self-clear: ran, results written */
        armed_done++;
        led_bottom(armed_done, armed_total);   /* fraction of THIS run done */
    }
    led_bottom(1u, 1u);         /* amber full (also covers "none armed") */
    led_top(1u, 1u, 0u, 1u);    /* red full, green off -> top red = done */

    debug_write("[probe] ########## RUN DONE ##########\r\n");
}
