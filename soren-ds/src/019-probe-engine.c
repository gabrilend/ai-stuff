/* {{{ the write allowlist
 *
 * Writes are confined to the chip's peripheral register space, so
 * a typo'd address cannot scribble over DRAM or the kernel. The
 * range covers the GRF / CRU / PMU blocks (0xFDC0_0000 region) and
 * the main peripheral window (0xFE00_0000 region) catalogued in
 * docs/016-physical-memory-map.md. Reads are not restricted. */
static int write_allowed(uint32_t addr)
{
    if (addr >= 0xFDC00000u && addr < 0xFDE00000u) return 1; /* GRF/CRU/PMU */
    if (addr >= 0xFE000000u && addr < 0xFE800000u) return 1; /* peripherals */
    return 0;
}
