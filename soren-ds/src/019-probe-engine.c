/* {{{ memtest — bounded DRAM pattern test (the DRAM-walk CALL)
 *
 * Tests a fixed 1 MB window at the 1 GB mark of DRAM. That address
 * is chosen to sit far clear of the kernel image (loaded at
 * 0x0200_0000), its stack and .bss, and the page allocator's pool
 * (all in low DRAM), so the test never scribbles on anything live.
 * It writes four marching patterns plus an address-in-address pass
 * and verifies every read-back, reporting the first failing word.
 *
 * This lives in C because a probe script cannot W into DRAM — the
 * write allowlist is peripheral-only on purpose, so a stray W can't
 * corrupt RAM. The DRAM walk is a deliberate, bounded operation, so
 * it belongs behind a CALL. */
#define MEMTEST_BASE  0x40000000u
#define MEMTEST_WORDS (0x100000u / 4u)   /* 1 MB */

static int memtest_check(uint32_t pat)
{
    volatile uint32_t *m = (volatile uint32_t *)(uintptr_t)MEMTEST_BASE;
    for (uint32_t i = 0; i < MEMTEST_WORDS; i++) m[i] = pat;
    for (uint32_t i = 0; i < MEMTEST_WORDS; i++) {
        if (m[i] != pat) {
            debug_write("[probe]   FAIL at ");
            write_hex32(MEMTEST_BASE + i * 4u);
            debug_write(" got=");
            write_hex32(m[i]);
            debug_write(" want=");
            write_hex32(pat);
            debug_write("\r\n");
            return -1;
        }
    }
    return 0;
}

static void memtest_run(void)
{
    static const uint32_t pats[4] = {
        0x00000000u, 0xFFFFFFFFu, 0x55555555u, 0xAAAAAAAAu
    };
    debug_write("[probe] memtest: 1 MB @ 0x40000000\r\n");
    for (int p = 0; p < 4; p++) {
        debug_write("[probe]   pattern ");
        write_hex32(pats[p]);
        debug_write("\r\n");
        if (memtest_check(pats[p]) != 0) return;
    }
    /* Address-in-address: each word holds its own address. Catches
     * stuck address lines that the uniform patterns miss. */
    volatile uint32_t *m = (volatile uint32_t *)(uintptr_t)MEMTEST_BASE;
    for (uint32_t i = 0; i < MEMTEST_WORDS; i++) m[i] = MEMTEST_BASE + i * 4u;
    for (uint32_t i = 0; i < MEMTEST_WORDS; i++) {
        if (m[i] != MEMTEST_BASE + i * 4u) {
            debug_write("[probe]   FAIL addr-test at ");
            write_hex32(MEMTEST_BASE + i * 4u);
            debug_write(" got=");
            write_hex32(m[i]);
            debug_write("\r\n");
            return;
        }
    }
    debug_write("[probe] memtest PASS\r\n");
}
