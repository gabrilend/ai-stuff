static inline void mmio_w8 (uint32_t a, uint8_t  v) { *(volatile uint8_t  *)(uintptr_t)a = v; }

static void busy_delay(uint32_t n)
{
    volatile uint32_t r = n;
    while (r--) { __asm__ volatile ("nop"); }
}

/* {{{ helpers — tiny freestanding string / number parsing */

static int streq(const char *a, const char *b)
{
    while (*a && *b) { if (*a != *b) return 0; a++; b++; }
    return *a == *b;
}

/* Emit a 32-bit value as `0xXXXXXXXX` through debug_write. */
static void write_hex32(uint32_t v)
{
    static const char d[] = "0123456789ABCDEF";
    char buf[11];
    buf[0] = '0'; buf[1] = 'x';
    for (int i = 0; i < 8; i++) buf[2 + i] = d[(v >> ((7 - i) * 4)) & 0xFu];
    buf[10] = 0;
    debug_write(buf);
}

/* Skip spaces and tabs. */
static const char *skip_ws(const char *p)
{
    while (*p == ' ' || *p == '\t') p++;
    return p;
}

/* Read a whitespace-delimited token into out[], NUL-terminated.
 * Returns the token length and advances *pp past it. */
static int read_token(const char **pp, char *out, int max)
{
    const char *p = skip_ws(*pp);
    int n = 0;
    while (*p && *p != ' ' && *p != '\t' && n < max - 1) out[n++] = *p++;
    out[n] = 0;
    *pp = p;
    return n;
}

/* Parse a hex number (optional 0x prefix). Sets *ok to whether any
 * hex digits were consumed; advances *pp. */
static uint32_t parse_hex(const char **pp, int *ok)
{
    const char *p = skip_ws(*pp);
    if (p[0] == '0' && (p[1] == 'x' || p[1] == 'X')) p += 2;
    uint32_t v = 0;
    int digits = 0;
    for (;;) {
        char c = *p;
        int dgt;
        if (c >= '0' && c <= '9') dgt = c - '0';
        else if (c >= 'a' && c <= 'f') dgt = c - 'a' + 10;
        else if (c >= 'A' && c <= 'F') dgt = c - 'A' + 10;
        else break;
        v = (v << 4) | (uint32_t)dgt;
        p++; digits++;
    }
    *ok = (digits > 0);
    *pp = p;
    return v;
}

/* Parse a decimal number. */
static uint32_t parse_dec(const char **pp, int *ok)
{
    const char *p = skip_ws(*pp);
    uint32_t v = 0;
    int digits = 0;
    while (*p >= '0' && *p <= '9') { v = v * 10u + (uint32_t)(*p - '0'); p++; digits++; }
    *ok = (digits > 0);
    *pp = p;
    return v;
}

