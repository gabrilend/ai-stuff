/*
 * 019-probe-engine.c — compiled-in hardware probe battery (issue 110i)
 *
 * Turns a `--debug` build of the kernel into a self-running
 * diagnostic instrument. Every #AUTO-marked probe under input/probes/
 * is generated into a C array (scripts/embed-probes -> probe-list.inc)
 * and compiled in; on boot the kernel arms them from their #NEEDED
 * defaults and runs the armed ones in priority order (issue 110n),
 * logging results to the SD-backed debug log. A normal build
 * defines nothing, so this whole file compiles to an empty object and
 * a production image carries no probe code at all.
 *
 * The probe language is deliberately tiny and dumb — read a register,
 * write a register, dump a range, delay, check a value, or call a
 * whole driver routine by name. No arithmetic, no variables, no
 * control flow. Anything more complex belongs in C.
 *
 * Two safety boundaries keep an arbitrary-MMIO-write instrument from
 * bricking the device:
 *   - writes are only honoured for a probe whose #WRITES marker set
 *     its writes-enabled flag, so a read-only probe cannot poke
 *     anything by accident;
 *   - writes are confined to an allowlist of peripheral register
 *     windows; a write outside is logged and skipped.
 *
 * Reads are unrestricted (reading a register cannot change state).
 *
 * History: this began as an SD-card-driven interpreter the lab tech
 * wrote scripts onto and the kernel read back at boot. The delivery
 * moved in-tree once we accepted that a build flag is already a
 * rebuild (so the no-rebuild benefit was moot) and that we run every
 * probe each time (so there was nothing to select). The interpreter
 * and the script language carried over unchanged. See issue 110i.
 * A later refinement (110k) brought build-time selection back: a
 * per-probe #NEEDED bit keeps a probe compiled in but lets a given
 * build de-select it — selection at build time, which a flag already
 * permits, not the flash-time selection 110i rightly dropped.
 */

