-- {{{ local function escape()
local function escape(text)
  text = text:gsub("&", "&amp;"):gsub("<", "&lt;"):gsub(">", "&gt;")
  return text
end
-- }}}

-- {{{ local function highlight_lua()
-- Syntax highlighting, for Lua, done by hand.
--
-- Three passes over a line rather than a real lexer, because the thing being
-- highlighted is already correct Lua that a real compiler has read -- this only has to
-- make it easier to look at. A lexer would be right and would be a second parser to
-- keep in step with the language.
local function highlight_lua(code)
  local out = {}
  for line in (code .. "\n"):gmatch("(.-)\n") do
    local comment = line:match("^(.-)%-%-")
    local body, tail = line, nil
    if comment ~= nil then
      body = comment
      tail = line:sub(#comment + 1)
    end

    body = escape(body)
    body = body:gsub("(&quot;[^&]-&quot;)", "<span class='str'>%1</span>")
    body = body:gsub('(".-")', "<span class='str'>%1</span>")
    body = body:gsub("(%f[%w])(%d+%.?%d*)(%f[%W])", "%1<span class='num'>%2</span>%3")
    for _, word in ipairs({"local", "function", "end", "if", "then", "else", "elseif",
                           "for", "while", "do", "return", "and", "or", "not", "nil",
                           "true", "false", "in", "break", "repeat", "until"}) do
      body = body:gsub("(%f[%w])(" .. word .. ")(%f[%W])", "%1<span class='kw'>%2</span>%3")
    end

    if tail ~= nil then
      out[#out + 1] = body .. "<span class='cmt'>" .. escape(tail) .. "</span>"
    else
      out[#out + 1] = body
    end
  end
  return table.concat(out, "\n")
end
-- }}}

-- {{{ local function inline()
-- The inline half of Markdown, plus the one thing this project needs that Markdown
-- has no syntax for: **an issue number is a link.**
--
-- The documents mention issues by number roughly two hundred times, and following one
-- by hand means knowing the naming convention, guessing the description, and listing a
-- directory. So `issue 206` becomes a link, and so does a bare three-digit number in
-- a table cell that is obviously an issue.
local function inline(text, links)
  text = escape(text)

  -- Code first, so nothing else formats inside it.
  local spans = {}
  text = text:gsub("`([^`]+)`", function(code)
    spans[#spans + 1] = "<code>" .. code .. "</code>"
    return "\1" .. #spans .. "\1"
  end)

  text = text:gsub("%*%*([^*]+)%*%*", "<strong>%1</strong>")
  text = text:gsub("%*([^*]+)%*", "<em>%1</em>")

  -- Markdown links, rewritten to the generated page names.
  text = text:gsub("%[([^%]]+)%]%(([^)]+)%)", function(label, target)
    local page = target:match("([^/]+)%.md$")
    if page ~= nil then
      return "<a href='" .. page .. ".html'>" .. label .. "</a>"
    end
    return "<a href='" .. target .. "'>" .. label .. "</a>"
  end)

  -- And the issue numbers.
  text = text:gsub("(issues?%s+)(%d%d%d)", function(word, number)
    local target = links[number]
    if target == nil then
      return word .. number
    end
    return word .. "<a class='issue-link' href='" .. target .. ".html'>" .. number .. "</a>"
  end)

  text = text:gsub("\1(%d+)\1", function(index)
    return spans[tonumber(index)]
  end)
  return text
end
-- }}}

-- {{{ local function render()
-- Markdown to HTML. The subset this project actually writes, and nothing else.
--
-- Deliberately not a complete implementation. A full Markdown parser is a large thing
-- with many decisions in it, and every one of those decisions is a way for the
-- generated page to differ from what the author meant. This handles headings, lists,
-- tables, quotes, fenced code and rules -- which is everything in every document here,
-- checked by reading them.
local function render(markdown, links)
  local out = {}
  local in_list, in_table, in_code = false, false, false
  local code_buffer, code_kind = {}, ""

  local function close_list()
    if in_list then out[#out + 1] = "</ul>" ; in_list = false end
  end
  local function close_table()
    if in_table then out[#out + 1] = "</tbody></table>" ; in_table = false end
  end

  for line in (markdown .. "\n"):gmatch("(.-)\n") do
    if in_code then
      if line:match("^```") then
        in_code = false
        local body = table.concat(code_buffer, "\n")
        out[#out + 1] = "<pre><code>" ..
          ((code_kind == "lua") and highlight_lua(body) or escape(body)) .. "</code></pre>"
        code_buffer = {}
      else
        code_buffer[#code_buffer + 1] = line
      end
    elseif line:match("^```") then
      close_list() ; close_table()
      in_code = true
      code_kind = line:match("^```(%w*)") or ""
    elseif line:match("^%s*$") then
      close_list() ; close_table()
    elseif line:match("^#+%s") then
      close_list() ; close_table()
      local hashes, rest = line:match("^(#+)%s+(.*)$")
      local level = #hashes
      out[#out + 1] = string.format("<h%d>%s</h%d>", level, inline(rest, links), level)
    elseif line:match("^%-%-%-+%s*$") then
      close_list() ; close_table()
      out[#out + 1] = "<hr>"
    elseif line:match("^>%s?") then
      close_list() ; close_table()
      out[#out + 1] = "<blockquote><p>" .. inline(line:gsub("^>%s?", ""), links) .. "</p></blockquote>"
    elseif line:match("^%s*[-*]%s+") then
      close_table()
      if not in_list then out[#out + 1] = "<ul>" ; in_list = true end
      out[#out + 1] = "<li>" .. inline(line:gsub("^%s*[-*]%s+", ""), links) .. "</li>"
    elseif line:match("^%s*%d+%.%s+") then
      close_table()
      if not in_list then out[#out + 1] = "<ul>" ; in_list = true end
      out[#out + 1] = "<li>" .. inline(line:gsub("^%s*%d+%.%s+", ""), links) .. "</li>"
    elseif line:match("^|") then
      close_list()
      -- A separator row opens the body rather than producing a row of dashes.
      if line:match("^|[%s|:%-]+|%s*$") and in_table then
        out[#out + 1] = "</thead><tbody>"
      else
        local cells = {}
        for cell in line:gmatch("|([^|]*)") do
          cells[#cells + 1] = cell:match("^%s*(.-)%s*$")
        end
        -- The trailing empty cell after the final pipe.
        if cells[#cells] == "" then cells[#cells] = nil end
        if not in_table then
          out[#out + 1] = "<table><thead>"
          in_table = true
          local row = {"<tr>"}
          for _, cell in ipairs(cells) do
            row[#row + 1] = "<th>" .. inline(cell, links) .. "</th>"
          end
          row[#row + 1] = "</tr>"
          out[#out + 1] = table.concat(row)
        else
          local row = {"<tr>"}
          for _, cell in ipairs(cells) do
            row[#row + 1] = "<td>" .. inline(cell, links) .. "</td>"
          end
          row[#row + 1] = "</tr>"
          out[#out + 1] = table.concat(row)
        end
      end
    else
      close_list() ; close_table()
      out[#out + 1] = "<p>" .. inline(line, links) .. "</p>"
    end
  end
  close_list() ; close_table()
  return table.concat(out, "\n")
end
-- }}}

M.render = render

-- {{{ local function list_files()
-- Every file matching a pattern in a directory, sorted, without shelling out for a
-- listing per directory.
local function list_files(directory, pattern)
  local names = {}
  local pipe = io.popen("ls -1 '" .. directory .. "' 2>/dev/null")
  if pipe == nil then
    return names
  end
  for name in pipe:lines() do
    if name:match(pattern) then
      names[#names + 1] = name
    end
  end
  pipe:close()
  table.sort(names)
  return names
end
-- }}}

-- {{{ local function map_drawing()
-- The map, as an SVG, on the front page.
--
-- Drawn from the map builder rather than from a picture of it, so it cannot go stale.
-- That is the same rule as everything else here: the thing is the data, the page is a
-- view of it, and a view nobody generates is a view that will be wrong.
local function map_drawing(map)
  local out = {}
  local size = 460
  local bounds = map.bounds
  local span = math.max(bounds.max_x - bounds.min_x, bounds.max_y - bounds.min_y)
  local function place(x, y)
    return (x - bounds.min_x) / span * size, (y - bounds.min_y) / span * size
  end

  out[#out + 1] = string.format(
    "<svg viewBox='-16 -16 %d %d' width='%d' height='%d'>", size + 32, size + 32, size, size)

  -- The connectors first, under everything: the ground the jungle used to occupy.
  for _, connector in ipairs(map.connector) do
    local points = {}
    for _, node_id in ipairs(connector.path) do
      local x, y = place(map.node[node_id].x, map.node[node_id].y)
      points[#points + 1] = string.format("%.1f,%.1f", x, y)
    end
    out[#out + 1] = "<polyline points='" .. table.concat(points, " ") ..
      "' fill='none' stroke='#2a2732' stroke-width='7'/>"
  end

  local lane_colour = {"#3a4150", "#46506a", "#3a4150"}
  for index, lane in ipairs(map.lane) do
    local points = {}
    for _, node_id in ipairs(lane.path) do
      local x, y = place(map.node[node_id].x, map.node[node_id].y)
      points[#points + 1] = string.format("%.1f,%.1f", x, y)
    end
    out[#out + 1] = string.format(
      "<polyline points='%s' fill='none' stroke='%s' stroke-width='%.1f' " ..
      "stroke-linejoin='round' stroke-linecap='round'/>",
      table.concat(points, " "), lane_colour[index],
      lane.width / span * size)
  end

  -- The stone, in each team's own colour.
  for _, site in ipairs(map.site) do
    local node = map.node[site.node]
    local x, y = place(node.x, node.y)
    local colour = (site.team == 1) and "#f5a83d" or "#5cc7ee"
    if site.kind == 3 then
      out[#out + 1] = string.format(
        "<circle cx='%.1f' cy='%.1f' r='9' fill='none' stroke='%s' stroke-width='2.5'/>",
        x, y, colour)
      out[#out + 1] = string.format(
        "<circle cx='%.1f' cy='%.1f' r='3.5' fill='%s'/>", x, y, colour)
    else
      out[#out + 1] = string.format(
        "<rect x='%.1f' y='%.1f' width='7' height='7' fill='%s' opacity='0.85'/>",
        x - 3.5, y - 3.5, colour)
    end
  end

  -- And the junctions, which are the only points on the map where anything chooses.
  for _, lane in ipairs(map.lane) do
    local node = map.node[lane.junction[1]]
    local x, y = place(node.x, node.y)
    out[#out + 1] = string.format(
      "<circle cx='%.1f' cy='%.1f' r='6' fill='none' stroke='#7d8492' " ..
      "stroke-width='1.5' stroke-dasharray='3 2'/>", x, y)
  end

  out[#out + 1] = "</svg>"
  return table.concat(out, "\n")
end
-- }}}

