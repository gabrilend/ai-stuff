-- {{{ function M.build()
-- Walks every document and writes the site.
function M.build(root, modules)
  local out_dir = root .. "/docs/HTML"
  os.execute("mkdir -p '" .. out_dir .. "'")

  -- What there is to write, and where each thing came from.
  -- **The issue pattern allows a letter after the number**, because a large issue is
  -- broken into sub-issues named 211a, 211b and so on -- a convention this project has
  -- used for a while and which this page silently did not know about, so every
  -- sub-issue ever written was unreachable from the documentation it belongs to.
  --
  -- And the two un-numbered documents are named outright. The queue and the balance log
  -- are the two most-read files in the project and neither matches a numbered pattern,
  -- because neither is a numbered document -- they are ledgers, and a ledger does not
  -- have a place in a reading order. That is not a reason for them to be missing from
  -- the only browsable copy of everything.
  local sections = {
    {title = "start here", dir = "notes", pattern = "^[a-z].*$", plain = true},
    {title = "the queue", dir = "issues", pattern = "^work%-queue%.md$"},
    {title = "the design", dir = "docs", pattern = "^%d%d%d%-.*%.md$"},
    {title = "the ledger", dir = "docs", pattern = "^balance%-updates%.md$"},
    {title = "issues", dir = "issues", pattern = "^%d%d%d%a?%-.*%.md$"},
    {title = "progress", dir = "issues", pattern = "^phase%-%d%-progress%.md$"},
    {title = "the simulation", dir = "src", pattern = "^%d%d%d%-.*%.info%.md$"},
    {title = "the catalogues", dir = "assets", pattern = "^%d%d%d%-.*%.info%.md$"},
    {title = "the tests", dir = "tests", pattern = "^%d%d%d%-.*%.info%.md$"},
  }

  -- Every issue number, so a mention of one anywhere becomes a link.
  local links = {}
  for _, name in ipairs(list_files(root .. "/issues", "^%d%d%d%a?%-.*%.md$")) do
    -- Keyed by the number **and** by the number plus its letter, so that both "211" and
    -- "211c" in a sentence become links to the right pages. The bare number wins for
    -- itself because a parent issue is what "211" means; a sub-issue is only ever
    -- referred to with its letter attached.
    local lettered = name:match("^(%d%d%d%a)%-")
    if lettered ~= nil then
      links[lettered] = name:gsub("%.md$", "")
    else
      links[name:sub(1, 3)] = name:gsub("%.md$", "")
    end
  end

  local pages = {}
  for _, section in ipairs(sections) do
    local entries = {}
    for _, name in ipairs(list_files(root .. "/" .. section.dir, section.pattern)) do
      local handle = io.open(root .. "/" .. section.dir .. "/" .. name, "r")
      if handle ~= nil then
        local body = handle:read("*a")
        handle:close()
        local slug = name:gsub("%.md$", "")
        local title = body:match("^#%s+(.-)\n") or slug
        entries[#entries + 1] = {slug = slug, title = title, body = body,
                                 plain = section.plain}
      end
    end
    if #entries > 0 then
      pages[#pages + 1] = {title = section.title, entries = entries}
    end
  end

  -- The contents rail, identical on every page, with the current one marked.
  local function contents_for(current)
    local out = {"<nav id='contents'>",
      "<h1>hero-less-moba</h1>",
      "<p class='tagline'>a lane-pushing game with the heroes subtracted out</p>",
      "<input id='filter' placeholder='filter&hellip;' autocomplete='off'>",
      "<a href='index.html'" .. ((current == "index") and " class='here'" or "") ..
        ">the front page</a>"}
    for _, section in ipairs(pages) do
      out[#out + 1] = "<section><h2>" .. section.title .. "</h2>"
      for _, entry in ipairs(section.entries) do
        local index = entry.slug:match("^(%d%d%d)")
        -- Strip the leading index and dash from a title, so the rail reads as names
        -- rather than as numbered names.
        --
        -- **Not with a character class.** Lua patterns are bytes, so `[-—]` is a class
        -- containing the three separate bytes of an em-dash -- and it will happily
        -- match one of them and leave the other two, producing a file that is no
        -- longer valid UTF-8. Every generated page was corrupt in exactly that way
        -- before this comment existed.
        local label = entry.title:gsub("^%d%d%d%s*", "")
        label = label:gsub("^\226\128\148%s*", "")   -- an em-dash
        label = label:gsub("^%-%s*", "")
        out[#out + 1] = string.format(
          "<a href='%s.html'%s>%s%s</a>", entry.slug,
          (current == entry.slug) and " class='here'" or "",
          index and ("<span class='index'>" .. index .. "</span>") or "",
          escape(label))
      end
      out[#out + 1] = "</section>"
    end
    out[#out + 1] = "</nav>"
    return table.concat(out, "\n")
  end

  local FILTER_SCRIPT = [[
<script>
// Filtering the contents. The only script on the page, and it exists because there
// are more than eighty documents here and scrolling a list of eighty things to find
// one is not navigation.
var box = document.getElementById('filter');
box.addEventListener('input', function () {
  var want = box.value.toLowerCase();
  var rail = document.getElementById('contents');
  rail.querySelectorAll('section').forEach(function (section) {
    var shown = 0;
    section.querySelectorAll('a').forEach(function (link) {
      var match = link.textContent.toLowerCase().indexOf(want) !== -1;
      link.style.display = match ? '' : 'none';
      if (match) { shown++; }
    });
    section.style.display = shown ? '' : 'none';
  });
});
</script>
]]

  local function write_page(slug, title, body_html)
    local handle = io.open(out_dir .. "/" .. slug .. ".html", "w")
    handle:write("<!doctype html><html lang='en'><head><meta charset='utf-8'>")
    handle:write("<meta name='viewport' content='width=device-width,initial-scale=1'>")
    handle:write("<title>" .. escape(title) .. " -- hero-less-moba</title>")
    handle:write("<style>" .. M.PALETTE .. M.STYLE .. "</style></head><body>")
    handle:write("<div id='shell'>")
    handle:write(contents_for(slug))
    handle:write("<main id='page'>")
    handle:write(body_html)
    handle:write("<footer>Generated from the Markdown by <code>" ..
      "064-the-documentation-becomes-html.lua</code>. The Markdown is the data; " ..
      "this is a view of it. Do not edit these pages -- edit the documents and " ..
      "run <code>./build-documentation</code>.</footer>")
    handle:write("</main></div>" .. FILTER_SCRIPT .. "</body></html>")
    handle:close()
  end

  local written = 0
  for _, section in ipairs(pages) do
    for _, entry in ipairs(section.entries) do
      local html
      if entry.plain then
        -- notes/ holds the visions, which are prose rather than Markdown and whose
        -- line breaks are the author's. They are shown as written.
        html = "<h1>" .. escape(entry.slug) .. "</h1><pre><code>" ..
               escape(entry.body) .. "</code></pre>"
      else
        html = render(entry.body, links)
      end
      write_page(entry.slug, entry.title, html)
      written = written + 1
    end
  end

  -- The front page, which is the only one with pictures on it.
  local parameters = modules.match_parameters.load()
  local map = modules.map_builder.build(parameters)

  local front = {}
  front[#front + 1] = "<h1>hero-less-moba</h1>"
  front[#front + 1] = "<p>Picture a lane-pusher, and subtract the heroes, the jungle " ..
    "and the items. What is left is a great many small bodies walking at each other " ..
    "and grinding to a halt in the middle -- which is not a game. So the things taken " ..
    "out are replaced by <strong>one shared chest of upgrades that three people argue " ..
    "over</strong>, and the argument is the game.</p>"
  front[#front + 1] = "<h2>The ground</h2>"
  front[#front + 1] = "<figure>" .. map_drawing(map) ..
    "<figcaption>Two bases facing each other across one diagonal; the three junctions " ..
    "on the other. Drawn from the map builder, so it cannot go stale.</figcaption></figure>"
  front[#front + 1] = "<h2>The shape of a match</h2>"
  front[#front + 1] = "<figure>" .. phase_drawing(parameters.boon.timing) ..
    "<figcaption>Three times the board comes apart, and the third time nothing " ..
    "saves it.</figcaption></figure>"
  front[#front + 1] = "<h2>Where to start</h2>"
  front[#front + 1] = "<ul>" ..
    "<li><a href='vision.html'>The vision</a> -- where all of this came from, in the " ..
    "author's own words.</li>" ..
    "<li><a href='001-what-this-game-is.html'>What this game is</a> -- the subtraction, " ..
    "and the three layers that replace what was taken.</li>" ..
    "<li><a href='019-roadmap.html'>The roadmap</a> -- nine phases, which are clusters " ..
    "of functionality rather than a schedule.</li>" ..
    "<li><a href='020-open-questions.html'>Open questions</a> -- every unresolved " ..
    "decision, and the reasoning behind every resolved one.</li>" ..
    "</ul>"
  front[#front + 1] = "<h2>Everything else</h2>"
  front[#front + 1] = "<p>Down the left. Every page here is reachable from every " ..
    "other, every issue number is a link, and the filter at the top of the rail " ..
    "searches all of it.</p>"

  write_page("index", "hero-less-moba", table.concat(front, "\n"))
  written = written + 1

  return written, out_dir
end
