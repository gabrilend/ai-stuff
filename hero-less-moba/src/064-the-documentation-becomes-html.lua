-- 064-the-documentation-becomes-html.lua
--
-- Every document, issue and companion, turned into pages you can browse.
--
-- ## The same separation, one level up
--
-- **The Markdown is the data and the HTML is a view of it**, generated by a tool
-- rather than maintained by hand. That is the same rule the simulation and the viewer
-- follow, applied to the project's own prose -- and for the same reason: a hand-kept
-- second copy of anything is a copy that will disagree with the first.
--
-- ## What it is for
--
-- This project is read far more than it is run. There are more words in it than code,
-- the words came first, and reconstructing the software means reading them. But they
-- reference each other constantly and a directory of files is a bad way to follow a
-- reference -- so: every page reachable from every other, a table of contents down
-- the side, and **every issue number a link**.
--
-- That last one matters more than it sounds. The documents mention issues by number
-- roughly two hundred times, and following one by hand means knowing the naming
-- convention, guessing the description, and listing a directory.

