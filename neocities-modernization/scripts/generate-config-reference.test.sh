#!/usr/bin/env bash
# generate-config-reference.test.sh -- proves the config reference generator
# writes each section of a config file into the doc, leaves every line outside
# its marked region alone, reports staleness without writing, and refuses a doc
# that has no markers rather than overwriting it whole. It runs the real
# generator against a throwaway project in RAM.
#
# Run: bash scripts/generate-config-reference.test.sh [project-dir]

set -u
DIR="/mnt/mtwo/programming/ai-stuff/neocities-modernization"
if [ -n "${1:-}" ]; then
    DIR="$1"
fi

"${DIR}/scripts/ensure-tmp-symlink" "${DIR}" >/dev/null
SCRATCH="${DIR}/tmp/shared-memory/generate-config-reference-test"
rm -rf "${SCRATCH}"
mkdir -p "${SCRATCH}/docs"
GENERATOR="${DIR}/scripts/generate-config-reference"
DOC="${SCRATCH}/docs/config-reference.md"
BEGIN='<!-- BEGIN section reference: generated by scripts/generate-config-reference; edit config.lua'"'"'s comments, not this -->'
END='<!-- END section reference -->'

pass=0; fail=0
# {{{ check
# check <label> <command...>: passes when the command succeeds.
check() {
    local label="$1"
    shift
    if "$@"; then pass=$((pass+1)); echo "  ok   - ${label}"
    else fail=$((fail+1)); echo "  FAIL - ${label}"; fi
}
# }}}

# {{{ the throwaway project
cat > "${SCRATCH}/config.lua" <<'EOF'
return {
    -- {{{ alpha
    -- The alpha section explains itself here.
    -- Read by: src/alpha.lua
    alpha = {
        width = 80,              -- How wide things are
        -- A note written above the setting.
        name = "box",
    },
    -- }}}

    -- A plain list with a comment.
    beta = {"one", "two"},
}
EOF
{
    echo "# Title written by hand"
    echo
    echo "${BEGIN}"
    echo "stale generated text"
    echo "${END}"
    echo
    echo "## Guide written by hand"
} > "${DOC}"
# }}}

"${GENERATOR}" "${SCRATCH}" > /dev/null
check "text above the region is kept"          grep -q '^# Title written by hand$' "${DOC}"
check "text below the region is kept"          grep -q '^## Guide written by hand$' "${DOC}"
check "old generated text is replaced"         test "$(grep -c 'stale generated text' "${DOC}")" -eq 0
check "a section gets a heading"               grep -q '^### alpha$' "${DOC}"
check "a section gets its comment"             grep -q 'The alpha section explains itself here' "${DOC}"
check "a setting gets its beside-comment"      grep -q '^| `width` | 80 | How wide things are |$' "${DOC}"
check "a setting gets its above-comment"       grep -q '^| `name` | "box" | A note written above the setting. |$' "${DOC}"
check "a list is shown whole"                  grep -q '^Current value: list of 2$' "${DOC}"
check "sections keep the file's order"         test "$(grep -n '^### ' "${DOC}" | head -1 | cut -d: -f2)" = "### alpha"

"${GENERATOR}" "${SCRATCH}" --check > /dev/null
check "--check passes right after writing"     test $? -eq 0

sed -i 's/width = 80/width = 81/' "${SCRATCH}/config.lua"
BEFORE="$(md5sum < "${DOC}")"
"${GENERATOR}" "${SCRATCH}" --check > /dev/null
status=$?
check "--check exits 1 when config changed"    test "${status}" -eq 1
check "--check writes nothing"                 test "$(md5sum < "${DOC}")" = "${BEFORE}"

printf '# no markers here\n' > "${DOC}"
"${GENERATOR}" "${SCRATCH}" > /dev/null 2>&1
status=$?
check "a doc without markers is refused"       test "${status}" -eq 2
check "the refused doc is untouched"           test "$(cat "${DOC}")" = "# no markers here"

rm -rf "${SCRATCH}"
echo "passed ${pass}, failed ${fail}"
[ "${fail}" -eq 0 ]
