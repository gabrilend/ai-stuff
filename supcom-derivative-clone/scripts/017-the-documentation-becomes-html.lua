-- {{{ local function escape()
local function escape(text)
  text = text:gsub("&", "&amp;"):gsub("<", "&lt;"):gsub(">", "&gt;")
  return text
end
-- }}}

-- {{{ local function highlight_lua()
-- Syntax highlighting, for Lua, done by hand. Three passes over a line rather
-- than a real lexer, because the thing being highlighted is already correct Lua
-- that a real compiler has read -- this only has to make it easier to look at.
local function highlight_lua(code)
  local out = {}
  for line in (code .. "\n"):gmatch("(.-)\n") do
    local comment = line:match("^(.-)%-%-")
    local body, tail = line, nil
    if comment ~= nil then
      body = comment
      tail = line:sub(#comment + 1)
    end

    body = escape(body)
    body = body:gsub('(".-")', "<span class='str'>%1</span>")
    body = body:gsub("(%f[%w])(%d+%.?%d*)(%f[%W])", "%1<span class='num'>%2</span>%3")
    for _, word in ipairs({"local", "function", "end", "if", "then", "else", "elseif",
                           "for", "while", "do", "return", "and", "or", "not", "nil",
                           "true", "false", "in", "break", "repeat", "until"}) do
      body = body:gsub("(%f[%w])(" .. word .. ")(%f[%W])", "%1<span class='kw'>%2</span>%3")
    end

    if tail ~= nil then
      out[#out + 1] = body .. "<span class='cmt'>" .. escape(tail) .. "</span>"
    else
      out[#out + 1] = body
    end
  end
  return table.concat(out, "\n")
end
-- }}}

-- {{{ local function highlight_shell()
-- The same for shell: comments and strings, nothing more. Enough to read a
-- script's explanatory header apart from its commands.
local function highlight_shell(code)
  local out = {}
  for line in (code .. "\n"):gmatch("(.-)\n") do
    local body, tail = line:match("^(.-)(#.*)$")
    if body == nil then body = line end
    body = escape(body)
    body = body:gsub('(".-")', "<span class='str'>%1</span>")
    body = body:gsub("('.-')", "<span class='str'>%1</span>")
    if tail ~= nil then
      out[#out + 1] = body .. "<span class='cmt'>" .. escape(tail) .. "</span>"
    else
      out[#out + 1] = body
    end
  end
  return table.concat(out, "\n")
end
-- }}}

