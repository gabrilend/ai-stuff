-- 017-the-documentation-becomes-html.lua
--
-- Every document, issue, companion and test, turned into pages you can browse.
--
-- ## The same separation, one level up
--
-- **The Markdown is the data and the HTML is a view of it**, generated by a tool
-- rather than maintained by hand. That is the same rule the simulation and the
-- viewer follow, applied to the project's own prose -- and for the same reason: a
-- hand-kept second copy of anything is a copy that will disagree with the first.
--
-- ## What it is for
--
-- This project is read far more than it is run. There are more words in it than
-- code, the words came first, and reconstructing the software means reading them.
-- But they reference each other constantly and a directory of files is a bad way
-- to follow a reference -- so: every page reachable from every other, a table of
-- contents down the side that can be filtered, **every issue number a link**, and
-- the ideas the design rests on drawn as things you can push on.
--
-- ## What it never does
--
-- It never runs a command. The output directory is made by the shell wrapper that
-- calls this; everything here is a read of a directory listing or a write of one
-- file. It never emits a dead link: a Markdown link to a file that is not there is
-- collected as an error and the run fails at the end, naming every one.
--
-- Usage:
--   luajit scripts/017-the-documentation-becomes-html.lua --dir /path/to/project

