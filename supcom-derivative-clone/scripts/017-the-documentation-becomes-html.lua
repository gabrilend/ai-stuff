-- {{{ local function render()
-- Markdown to HTML. The subset this project actually writes, and nothing else:
-- headings, lists, tables, quotes, fenced code, rules, and the inline marks. A
-- line "<!-- toy: name -->" is replaced by the named interactive piece.
local function render(markdown, links, report, page_name)
  local out = {}
  local in_list, in_table, in_code = false, false, false
  local code_buffer, code_kind = {}, ""

  local function close_list()
    if in_list then out[#out + 1] = "</" .. in_list .. ">" ; in_list = false end
  end
  local function close_table()
    if in_table then out[#out + 1] = "</tbody></table>" ; in_table = false end
  end
  local function line_inline(text)
    return inline(text, links, report, page_name)
  end

  for line in (markdown .. "\n"):gmatch("(.-)\n") do
    if in_code then
      if line:match("^```") then
        in_code = false
        local body = table.concat(code_buffer, "\n")
        local painter = HIGHLIGHT[code_kind]
        out[#out + 1] = "<pre><code>" .. (painter and painter(body) or escape(body)) .. "</code></pre>"
        code_buffer = {}
      else
        code_buffer[#code_buffer + 1] = line
      end
    elseif line:match("^```") then
      close_list() ; close_table()
      in_code = true
      code_kind = line:match("^```(%w*)") or ""
    elseif line:match("^<!%-%- toy: ([%w%-]+) %-%->%s*$") then
      close_list() ; close_table()
      out[#out + 1] = toy_html(line:match("^<!%-%- toy: ([%w%-]+) %-%->"), report, page_name)
    elseif line:match("^%s*$") then
      close_list() ; close_table()
    elseif line:match("^#+%s") then
      close_list() ; close_table()
      local hashes, rest = line:match("^(#+)%s+(.*)$")
      local level = #hashes
      out[#out + 1] = string.format("<h%d>%s</h%d>", level, line_inline(rest), level)
    elseif line:match("^%-%-%-+%s*$") then
      close_list() ; close_table()
      out[#out + 1] = "<hr>"
    elseif line:match("^>%s?") then
      close_list() ; close_table()
      out[#out + 1] = "<blockquote><p>" .. line_inline((line:gsub("^>%s?", ""))) .. "</p></blockquote>"
    elseif line:match("^%s*[-*]%s+") then
      close_table()
      if not in_list then out[#out + 1] = "<ul>" ; in_list = "ul" end
      out[#out + 1] = "<li>" .. line_inline((line:gsub("^%s*[-*]%s+", ""))) .. "</li>"
    elseif line:match("^%s*%d+%.%s+") then
      close_table()
      if not in_list then out[#out + 1] = "<ol>" ; in_list = "ol" end
      out[#out + 1] = "<li>" .. line_inline((line:gsub("^%s*%d+%.%s+", ""))) .. "</li>"
    elseif in_list and line:match("^%s%s+%S") then
      -- A continuation line of a list item, indented. Joined to the item above.
      out[#out] = out[#out]:gsub("</li>$", " " .. line_inline((line:gsub("^%s+", ""))) .. "</li>")
    elseif line:match("^|") then
      close_list()
      if line:match("^|[%s|:%-]+|%s*$") and in_table then
        out[#out + 1] = "</thead><tbody>"
      else
        local cells = {}
        for cell in line:gmatch("|([^|]*)") do
          cells[#cells + 1] = cell:match("^%s*(.-)%s*$")
        end
        if cells[#cells] == "" then cells[#cells] = nil end
        local tag = "td"
        if not in_table then
          out[#out + 1] = "<table><thead>"
          in_table = true
          tag = "th"
        end
        local row = {"<tr>"}
        for _, cell in ipairs(cells) do
          -- A cell that is exactly an issue number is a link to the issue, which
          -- is what makes the roadmap and the progress tables navigable.
          local number = cell:match("^(%d%d%d%l?)$")
          if number ~= nil and links.issue[number] ~= nil then
            row[#row + 1] = "<" .. tag .. "><a class='issue-link' href='" ..
              links.issue[number] .. ".html'>" .. number .. "</a></" .. tag .. ">"
          else
            row[#row + 1] = "<" .. tag .. ">" .. line_inline(cell) .. "</" .. tag .. ">"
          end
        end
        row[#row + 1] = "</tr>"
        out[#out + 1] = table.concat(row)
      end
    else
      close_list() ; close_table()
      out[#out + 1] = "<p>" .. line_inline(line) .. "</p>"
    end
  end
  close_list() ; close_table()
  return table.concat(out, "\n")
end
-- }}}

M.render = render

-- {{{ local function list_files()
-- Every file matching a pattern in a directory, sorted. One read-only listing per
-- directory, and nothing else is ever run.
local function list_files(directory, pattern)
  local names = {}
  local pipe = io.popen("ls -1 '" .. directory .. "' 2>/dev/null")
  if pipe == nil then
    return names
  end
  for name in pipe:lines() do
    if name:match(pattern) then
      names[#names + 1] = name
    end
  end
  pipe:close()
  table.sort(names)
  return names
end
-- }}}

-- {{{ local function read_file()
local function read_file(path)
  local handle = io.open(path, "r")
  if handle == nil then return nil end
  local text = handle:read("*a")
  handle:close()
  return text
end
-- }}}

-- {{{ local function status_of_issues()
-- Every issue's status, read off the phase progress tables, so an issue page can
-- wear a badge that agrees with the tracker rather than with itself.
local function status_of_issues(root)
  local status = {}
  for _, name in ipairs(list_files(root .. "/issues", "^phase%-%d%-progress%.md$")) do
    local text = read_file(root .. "/issues/" .. name) or ""
    for number, state in text:gmatch("\n| (%d%d%d%l?) | [^|]* | ([^|]*) |") do
      status[number] = state:match("^%s*(.-)%s*$")
    end
  end
  return status
end
-- }}}

-- {{{ function M.build()
-- Walks every document and writes the site. Returns the count written and where;
-- raises with every unresolved reference if there were any.
function M.build(root)
  local out_dir = root .. "/docs/HTML"
  local report = {}

  local sections = {
    {title = "start here", dir = "notes", pattern = "^[a-z][^.]*$", plain = true},
    {title = "the design", dir = "docs", pattern = "^%d%d%d%-.*%.md$"},
    {title = "the ledgers", dir = "docs", pattern = "^[a-z][%w%-]*%.md$"},
    {title = "issues", dir = "issues", pattern = "^%d%d%d%l?%-.*%.md$"},
    {title = "completed", dir = "issues/completed", pattern = "^%d%d%d%l?%-.*%.md$"},
    {title = "progress", dir = "issues", pattern = "^phase%-%d%-progress%.md$"},
    {title = "the tests", dir = "tests", pattern = "^%d%d%d%-.*%.info%.md$"},
    {title = "the tools", dir = "scripts", pattern = "^%d%d%d%-.*%.info%.md$"},
    {title = "the simulation", dir = "src", pattern = "^%d%d%d%-.*%.info%.md$"},
    {title = "the catalogues", dir = "assets", pattern = "^%d%d%d%-.*%.info%.md$"},
  }

  -- Every page's slug, every issue number, and every source stem, so that a
  -- mention anywhere becomes a link -- and a mention of something that is not
  -- there becomes an error.
  local links = {page = {}, issue = {}, stem = {}}
  local pages = {}
  for _, section in ipairs(sections) do
    local entries = {}
    for _, name in ipairs(list_files(root .. "/" .. section.dir, section.pattern)) do
      local body = read_file(root .. "/" .. section.dir .. "/" .. name)
      if body ~= nil then
        local slug = name:gsub("%.md$", "")
        local title = body:match("^#%s+(.-)\n") or slug
        entries[#entries + 1] = {slug = slug, title = title, body = body,
                                 plain = section.plain, section = section.title}
        links.page[slug] = slug
        local number = name:match("^(%d%d%d%l?)%-")
        if section.dir:match("^issues") and number ~= nil then
          links.issue[number] = slug
        end
        local stem = name:match("^%d%d%d%-(.*)%.info%.md$")
        if stem ~= nil then
          links.stem[stem] = slug
          links.stem[name:gsub("%.info%.md$", "")] = slug
        end
      end
    end
    if #entries > 0 then
      pages[#pages + 1] = {title = section.title, entries = entries}
    end
  end
  -- The README is a page too, linked from the front, and it links into docs/.
  local readme = read_file(root .. "/README.md")
  links.page["README"] = "README"
  local copying = read_file(root .. "/COPYING.md")
  links.page["COPYING"] = "COPYING"

  local status = status_of_issues(root)

  -- The contents rail, identical on every page, with the current one marked.
  local function contents_for(current)
    local out = {"<nav id='contents'>",
      "<h1>supcom-derivative-clone</h1>",
      "<p class='tagline'>a factory war on dunes where nothing is out of range</p>",
      "<input id='filter' placeholder='filter&hellip;' autocomplete='off'>",
      "<a href='index.html'" .. ((current == "index") and " class='here'" or "") ..
        ">the front page</a>",
      "<a href='README.html'" .. ((current == "README") and " class='here'" or "") ..
        ">the game design</a>"}
    for _, section in ipairs(pages) do
      out[#out + 1] = "<section><h2>" .. section.title .. "</h2>"
      for _, entry in ipairs(section.entries) do
        local index = entry.slug:match("^(%d%d%d%l?)")
        -- Strip the leading index and dash from a title, so the rail reads as
        -- names. Not with a character class: Lua patterns are bytes, and a class
        -- holding an em-dash matches one of its three bytes and leaves the rest,
        -- which corrupts the page's UTF-8.
        local label = entry.title:gsub("^%d%d%d%l?%s*", "")
        label = label:gsub("^\226\128\148%s*", "")
        label = label:gsub("^%-%s*", "")
        out[#out + 1] = string.format(
          "<a href='%s.html'%s>%s%s</a>", entry.slug,
          (current == entry.slug) and " class='here'" or "",
          index and ("<span class='index'>" .. index .. "</span>") or "",
          escape(label))
      end
      out[#out + 1] = "</section>"
    end
    out[#out + 1] = "</nav>"
    return table.concat(out, "\n")
  end

  local FILTER_SCRIPT = [[
<script>
// Filtering the contents. There are more than a hundred pages here and scrolling
// a list of a hundred things to find one is not navigation.
var box = document.getElementById('filter');
box.addEventListener('input', function () {
  var want = box.value.toLowerCase();
  var rail = document.getElementById('contents');
  rail.querySelectorAll('section').forEach(function (section) {
    var shown = 0;
    section.querySelectorAll('a').forEach(function (link) {
      var match = link.textContent.toLowerCase().indexOf(want) !== -1;
      link.style.display = match ? '' : 'none';
      if (match) { shown++; }
    });
    section.style.display = shown ? '' : 'none';
  });
});
</script>
]]

  local function write_page(slug, title, body_html)
    local handle = io.open(out_dir .. "/" .. slug .. ".html", "w")
    if handle == nil then
      error("cannot write " .. out_dir .. "/" .. slug .. ".html -- does docs/HTML exist?")
    end
    handle:write("<!doctype html><html lang='en'><head><meta charset='utf-8'>")
    handle:write("<meta name='viewport' content='width=device-width,initial-scale=1'>")
    handle:write("<title>" .. escape(title) .. " -- supcom-derivative-clone</title>")
    handle:write("<style>" .. M.PALETTE .. M.STYLE .. "</style></head><body>")
    handle:write("<div id='shell'>")
    handle:write(contents_for(slug))
    handle:write("<main id='page'>")
    handle:write(body_html)
    handle:write("<footer>Generated from the Markdown by <code>" ..
      "017-the-documentation-becomes-html.lua</code>. The Markdown is the data; " ..
      "this is a view of it. Do not edit these pages -- edit the documents and " ..
      "run <code>./build-documentation</code>.</footer>")
    handle:write("</main></div>" .. FILTER_SCRIPT .. "</body></html>")
    handle:close()
  end

  local written = 0
  for _, section in ipairs(pages) do
    for _, entry in ipairs(section.entries) do
      local html
      if entry.plain then
        -- notes/ holds the vision, which is prose rather than Markdown and whose
        -- line breaks are the author's. It is shown as written.
        html = "<h1>" .. escape(entry.slug) .. "</h1><pre><code>" ..
               escape(entry.body) .. "</code></pre>"
      else
        html = render(entry.body, links, report, entry.slug)
        -- An issue wears its tracker status as a badge on its heading.
        local number = entry.slug:match("^(%d%d%d%l?)%-")
        if number ~= nil and status[number] ~= nil and entry.section ~= "the design" then
          local state = status[number]
          local class = state:match("built") and "built"
                        or (state:match("progress") or state:match("part")) and "part" or "none"
          html = html:gsub("</h1>", " <span class='badge " .. class .. "'>" ..
                           escape(state) .. "</span></h1>", 1)
        end
      end
      write_page(entry.slug, entry.title, html)
      written = written + 1
    end
  end

  if readme ~= nil then
    write_page("README", "The game design", render(readme, links, report, "README"))
    written = written + 1
  end
  if copying ~= nil then
    write_page("COPYING", "Copying", render(copying, links, report, "COPYING"))
    written = written + 1
  end

  -- The front page: the two changes, one toy, and where to start.
  local front = {}
  front[#front + 1] = "<h1>supcom-derivative-clone</h1>"
  front[#front + 1] = "<p>Take a large-scale real-time strategy game and change two things. " ..
    "<strong>Nothing is out of range</strong> -- a gun fires at anything it can see, and " ..
    "what it can see is decided by the dunes between them. And <strong>units stop " ..
    "listening once they leave the factory</strong> -- a player lays a production line, " ..
    "draws its route in the sand once, and watches.</p>"
  front[#front + 1] = "<h2>The ground</h2>"
  front[#front + 1] = TOYS.sightline
  front[#front + 1] = "<h2>Where to start</h2>"
  front[#front + 1] = "<ul>" ..
    "<li><a href='vision.html'>The vision</a> -- where all of this came from, in the " ..
    "author's own words.</li>" ..
    "<li><a href='README.html'>The game design</a> -- the whole design on one page, " ..
    "and nothing about how it is built.</li>" ..
    "<li><a href='001-what-this-game-is.html'>What this game is</a> -- the two changes, " ..
    "everything that follows from them, and the vocabulary.</li>" ..
    "<li><a href='015-roadmap.html'>The roadmap</a> -- nine phases, which are clusters " ..
    "of functionality rather than a schedule.</li>" ..
    "<li><a href='016-open-questions.html'>Open questions</a> -- every unresolved " ..
    "decision, with its working ruling marked as one.</li>" ..
    "<li><a href='014-the-tests-come-first.html'>The tests come first</a> -- the " ..
    "contract between the tests and the source that does not exist yet.</li>" ..
    "</ul>"
  front[#front + 1] = "<h2>Everything else</h2>"
  front[#front + 1] = "<p>Down the left. Every page here is reachable from every " ..
    "other, every issue number is a link, and the filter at the top of the rail " ..
    "searches all of it.</p>"

  write_page("index", "supcom-derivative-clone", table.concat(front, "\n"))
  written = written + 1

  if #report > 0 then
    table.sort(report)
    error("the documentation has " .. #report .. " unresolved reference(s):\n  " ..
          table.concat(report, "\n  "))
  end

  return written, out_dir
end
-- }}}

-- {{{ the command line
-- Run as a program: --dir names the project root. Loaded as a module (no --dir),
-- it only exports.
local arguments = {...}
for index = 1, #arguments do
  if arguments[index] == "--dir" then
    local root = arguments[index + 1]
    if root == nil then
      io.stderr:write("--dir needs a path\n")
      os.exit(1)
    end
    local ok, written, where = pcall(M.build, root)
    if not ok then
      io.stderr:write(tostring(written), "\n")
      os.exit(1)
    end
    print(string.format("%d pages written to %s", written, where))
    print("open " .. where .. "/index.html")
    os.exit(0)
  end
end
-- }}}

return M
