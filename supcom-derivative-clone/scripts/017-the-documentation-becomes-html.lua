-- {{{ local function inline()
-- The inline half of Markdown, plus the things this project needs that Markdown
-- has no syntax for: **an issue number is a link**, a Markdown link to a
-- document becomes a link to the generated page, and a code span naming a source
-- file becomes a link to that file's companion.
--
-- `links` maps every issue number, page slug and source stem to a page slug.
-- `report` is where an unresolvable Markdown link is written down, because a dead
-- link in generated documentation is a bug in the source Markdown.
local function inline(text, links, report, page_name)
  text = escape(text)

  -- Code first, so nothing else formats inside it. A span that names a known
  -- companion is linked to it.
  local spans = {}
  text = text:gsub("`([^`]+)`", function(code)
    local stem = code:match("([%w%-]+)%.lua$") or code:match("^([%w%-]+)$")
    local target = stem and links.stem[stem]
    if target ~= nil then
      spans[#spans + 1] = "<a href='" .. target .. ".html'><code>" .. code .. "</code></a>"
    else
      spans[#spans + 1] = "<code>" .. code .. "</code>"
    end
    return "\1" .. #spans .. "\1"
  end)

  text = text:gsub("%*%*([^*]+)%*%*", "<strong>%1</strong>")
  text = text:gsub("%*([^*]+)%*", "<em>%1</em>")

  -- Markdown links, rewritten to the generated page names. A target ending in .md
  -- is a page here and must exist; anything else is passed through as written.
  text = text:gsub("%[([^%]]+)%]%(([^)]+)%)", function(label, target)
    local page = target:match("([^/]+)%.md$")
    if page ~= nil then
      if links.page[page] == nil then
        report[#report + 1] = page_name .. " links to " .. target .. ", which has no page"
      end
      return "<a href='" .. page .. ".html'>" .. label .. "</a>"
    end
    local bare = target:match("([^/]+)$")
    if links.page[bare] ~= nil then
      return "<a href='" .. bare .. ".html'>" .. label .. "</a>"
    end
    return "<a href='" .. target .. "'>" .. label .. "</a>"
  end)

  -- And the issue numbers: "issue 102", "issues 102, 103", "308a".
  text = text:gsub("(%f[%a][Ii]ssues?%s+)(%d%d%d%l?)", function(word, number)
    local target = links.issue[number]
    if target == nil then
      return word .. number
    end
    return word .. "<a class='issue-link' href='" .. target .. ".html'>" .. number .. "</a>"
  end)
  -- A comma-separated run after "issues" links each member.
  text = text:gsub("(</a>, )(%d%d%d%l?)", function(sep, number)
    local target = links.issue[number]
    if target == nil then return sep .. number end
    return sep .. "<a class='issue-link' href='" .. target .. ".html'>" .. number .. "</a>"
  end)

  text = text:gsub("\1(%d+)\1", function(index)
    return spans[tonumber(index)]
  end)
  return text
end
-- }}}

