-- {{{ local function full_listing()
-- Every number in the machine, with what produced it and what it is for. The
-- document this project's notation exists to make possible.
local function full_listing(L)
  local out = {}
  local function w(fmt, ...)
    out[#out + 1] = select("#", ...) > 0 and fmt:format(...) or fmt
  end
  w("# Every number in the machine")
  w("")
  w("*Generated by `097`. One row per symbol: what it is called, what it is")
  w("measured in, where it came from, what it comes to, and why it exists.*")
  w("")

  -- grouped by the blueprint that declares them, in blueprint order
  local by_bp, order = {}, {}
  for _, name in ipairs(L.order) do
    local d = L.decl[name]
    local k = d.blueprint.number
    if not by_bp[k] then by_bp[k] = { bp = d.blueprint, rows = {} }; order[#order + 1] = k end
    by_bp[k].rows[#by_bp[k].rows + 1] = d
  end
  table.sort(order)

  for _, k in ipairs(order) do
    local g = by_bp[k]
    w("## %s — %s", g.bp.number, g.bp.title)
    w("")
    w("| symbol | unit | kind | value | from | meaning |")
    w("|---|---|---|---|---|---|")
    for _, d in ipairs(g.rows) do
      local v = shown(L, d.name) or "unresolved"
      local from = (d.kind == "derived") and ("`" .. d.expr .. "`") or "—"
      w("| `%s` | %s | %s | %s | %s | %s |",
        d.name, d.unit, d.kind, v, from, d.meaning)
    end
    w("")
  end
  return table.concat(out, "\n") .. "\n"
end
-- }}}

-- {{{ function M.run()
function M.run(dir, opts)
  dir = dir or DIR
  opts = opts or {}
  local L = ledger.load(dir)
  local problems = {}

  local docs = {
    { path = dir .. "/docs/089-specification.md", body = render(L, SHEET, problems) },
    { path = dir .. "/docs/088-bill-of-materials.md", body = render(L, BOM, problems) },
    { path = dir .. "/docs/101-every-number.md", body = full_listing(L) },
  }
  if not opts.dry then
    for _, d in ipairs(docs) do
      local fh = assert(io.open(d.path, "w"))
      fh:write(d.body)
      fh:close()
    end
  end
  return { ledger = L, docs = docs, problems = problems, dry = opts.dry }
end
-- }}}

-- {{{ function M.report()
function M.report(R, out)
  out = out or io.stdout
  local function say(fmt, ...)
    out:write(select("#", ...) > 0 and fmt:format(...) or fmt, "\n")
  end
  say("")
  for _, d in ipairs(R.docs) do
    say("  %s  %s", R.dry and "would write" or "wrote      ", d.path:match("[^/]+$"))
  end
  if #R.problems > 0 then
    say("")
    say("  TEMPLATE -- names that did not resolve")
    say("  (a figure on a generated sheet must exist as a symbol somewhere;")
    say("  a blank here is a number that would appear only on the sheet)")
    for _, p in ipairs(R.problems) do say("    %s", p) end
    say("")
    return 1
  end
  say("")
  return 0
end
-- }}}

