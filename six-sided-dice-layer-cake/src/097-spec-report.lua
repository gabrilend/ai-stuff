-- 097-spec-report.lua
--
-- Produces the three documents whose content is entirely derived: the
-- specification sheet, the bill of materials, and a full listing of every
-- number in the machine with its name, its unit, its derivation and its reason.
--
-- For a general reader: the first two are for other people and the third is for
-- whoever is working on the design. The third is the one with nothing else like
-- it -- over a thousand quantities, each with the expression that produced it
-- and the sentence saying what it is, which is what the whole notation was for.
--
-- Nothing here invents a number. A template names symbols and the generator
-- substitutes; a name that does not resolve is an error and not a blank,
-- because the failure mode of a summary document is a figure that appears only
-- in it.

