-- {{{ local function shown()
-- A resolved value in a named unit, or in the unit its author declared it in.
-- A quantity printed in base units is correct and unreadable: a cube reported as
-- 0.06 m when every drawing says millimetres helps nobody.
local function shown(L, name, unit, digits)
  local q = L.value[name]
  if not q then return nil, ("%s does not resolve"):format(name) end
  local d = L.decl[name]
  local ok, s = pcall(units.format, q, unit or d.unit, digits or 4)
  if not ok then
    return nil, ("%s cannot be expressed in %s"):format(name, unit or d.unit)
  end
  return s
end
-- }}}

-- {{{ local function render()
-- Substitute {name} and {name:unit} in a template. An unresolved name raises
-- rather than leaving a gap, which is 089's C-089-1 enforced by the generator
-- that fills it.
local function render(L, text, problems)
  return (text:gsub("{([%w_]+):?([%w_%^%*/%(%)%-]*)}", function(name, unit)
    local s, err = shown(L, name, unit ~= "" and unit or nil)
    if not s then
      problems[#problems + 1] = err
      return "<<" .. name .. ">>"
    end
    return s
  end))
end
-- }}}

