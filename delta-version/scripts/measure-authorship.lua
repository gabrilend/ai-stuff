-- {{{ Repository rules
-- The second half of the measure reads the repository's own files -- only
-- those git tracks, so scratch space, build products and anything ignored are
-- out -- and sorts each into one of three piles, counted with the same
-- character rule as the transcripts:
--
--   notes   -- anything under a notes/ folder. The owner's rule: notes are
--              written by hand, so they join the person's side. Counted
--              wherever the folder sits, even under input/ (words-pdf keeps
--              its poems at input/notes/).
--   docs    -- documents, issue files included: every markdown file, and
--              plain-text files under docs/ or issues/ or named README.
--   source  -- program source: the extensions below, a few build files known
--              by name, and extension-less files that open with a #! line.
--
-- Left out entirely, in this order (the first rule that matches decides):
--   vendored   -- someone else's work (see below); counted apart, for the record
--   llm-transcripts/ -- the conversations, measured by the first half
--   docs/HTML/ -- a generated copy of the docs; counting it would count them twice
--   notes/     -- (not left out: taken here, before the next rule)
--   input/, output/ -- what a project reads and what it produces
--   backups/, archives/ -- copies, the same rule the project census uses
--   source/    -- an upstream clone kept by the upstream-patch system
--
-- A file whose exact contents appear more than once (a copy kept in two
-- places) is counted once, in the most personal pile it landed in:
-- notes, then docs, then source.
--
-- What "someone else's work" means follows the repository's COPYRIGHT file,
-- whose rule is: walk up to the nearest licence file, and read the file's own
-- header too. So:
--   * a directory holding a licence file that names a copyright holder other
--     than the owner (or carries a permissive grant such as MIT's "Permission
--     is hereby granted") is vendored, with everything under it;
--   * a source file whose first lines carry such a notice is vendored;
--   * the repository's top-level libs/ is vendored: the census already calls
--     it the shared third-party shelf.
-- Not the rule: "every libs/ folder is vendored". Most projects' libs/ hold
