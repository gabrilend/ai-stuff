-- {{{ Counting the repository's files

-- {{{ local function names_someone_else()
-- Does this text (a licence file, or a source file's opening lines) carry a
-- notice that someone other than the owner holds the rights? Line by line: a
-- line matching a foreign-notice shape counts unless it also carries one of
-- the not-foreign marks.
local function names_someone_else(text, line_limit)
    local seen = 0
    for line in (text .. "\n"):gmatch("([^\n]*)\n") do
        seen = seen + 1
        if line_limit and seen > line_limit then break end
        if matches_any(line, repo_rules.foreign_notices) then
            local ours = false
            for _, mark in ipairs(repo_rules.not_foreign) do
                if line:find(mark, 1, true) then ours = true; break end
            end
            if not ours then return true end
        end
    end
    return false
end
-- }}}

-- {{{ local function tracked_files()
-- Every path git tracks, relative to DIR. Read NUL-separated so that names
-- git would otherwise quote (spaces, accents) arrive exactly as they are.
local function tracked_files()
    local pipe = io.popen(string.format("git -C %q ls-files -z", DIR))
    if not pipe then error("could not list tracked files in " .. DIR, 0) end
    local listing = pipe:read("*a")
    pipe:close()
    local files = {}
    for path in listing:gmatch("([^%z]+)%z") do files[#files + 1] = path end
    return files
end
-- }}}

-- {{{ local function vendored_directories()
-- The folders the COPYRIGHT rule hands to someone else: each one holding a
-- tracked licence file that names another rights holder. The repository's
-- own root licence is the owner's by definition and is not read.
--
-- Also a web page saved from a browser, which is someone else's page: the
-- browser writes "Title.html" beside a "Title_files/" folder of its parts, so
-- a tracked path inside an "X_files/" folder marks that folder and the X.html
-- beside it. (Keyed in the same table; a file key is matched exactly.)
local function vendored_directories(files)
    local vendored = {}
    for _, path in ipairs(files) do
        local page_folder, page_name = path:match("^(.-)([^/]+)_files/")
        if page_folder then
            vendored[page_folder .. page_name .. "_files"] = true
            vendored[page_folder .. page_name .. ".html"] = true
        end
        local folder, name = path:match("^(.*)/([^/]+)$")
        if folder and matches_any(name, repo_rules.licence_file) then
            local handle = io.open(DIR .. "/" .. path, "rb")
            if handle then
                local text = handle:read("*a")
                handle:close()
                if names_someone_else(text) then vendored[folder] = true end
            end
        end
    end
    return vendored
end
-- }}}

-- {{{ local function classify_path()
-- Which pile a tracked path belongs to, from its path alone, or nil when it is
-- left out. "maybe_source" is an extension-less file that becomes source only
-- if it opens with #!, which the worker checks. The order is the order in the
-- Repository rules comment above; each branch notes what it decides.
local function classify_path(path, vendored)
    local segments = {}
    for segment in path:gmatch("[^/]+") do segments[#segments + 1] = segment end
    local name = segments[#segments]

    -- someone else's work: under a vendored folder, the top-level shelf, or
    -- a package manager's folder
    if repo_rules.vendored_top_level[segments[1]] and #segments > 1 then return "vendored" end
    if vendored[path] then return "vendored" end   -- a saved page's own .html
    for depth = 1, #segments - 1 do
        if vendored[table.concat(segments, "/", 1, depth)] then return "vendored" end
        if repo_rules.vendored_segments[segments[depth]] then return "vendored" end
    end

    -- a .bak file is a copy of something counted elsewhere
    if name:find(".bak", 1, true) then return nil end

    local in_notes, skipped, in_doc_folder = false, false, false
    for depth = 1, #segments - 1 do
        local segment = segments[depth]
        -- the conversations (and their backup folders, llm-transcripts-backup/),
        -- and the generated HTML copy of the docs: never
        if segment:find("^llm%-transcripts") then return nil end
        if segment == "HTML" and segments[depth - 1] == "docs" then return nil end
        if segment == "notes" then in_notes = true end
        if repo_rules.skipped_segments[segment] then skipped = true end
        if repo_rules.doc_text_folders[segment] then in_doc_folder = true end
    end
    -- notes win over input/ (hand-written poems kept as a project's input)
    if in_notes then return "notes" end
    if skipped then return nil end

    local extension = name:match("%.([^%./]+)$")
    if extension and repo_rules.doc_extensions[extension:lower()] then return "docs" end
    if extension == "txt" and (in_doc_folder or name:match("^README")) then return "docs" end
    if repo_rules.source_names[name] then return "source" end
    if extension and repo_rules.source_extensions[extension] then return "source" end
    -- a leading dot is a hidden file, not an extension-less script
    if not extension and not name:match("^%.") then return "maybe_source" end
    return nil
end
-- }}}

-- {{{ local function count_file()
-- One file's pile, content hash and character count, or nil when reading it
-- shows it does not belong after all. Four late decisions need the contents:
--   a NUL byte in the first 8 KB -> binary, left out
--   extension-less without #!   -> not a script, left out
--   a document holding exported conversation turns -> left out
--   source with a foreign notice in its opening lines -> vendored
local function count_file(category, path)
    local handle = io.open(DIR .. "/" .. path, "rb")
    if not handle then return nil end   -- a tracked file deleted from disk
    local text = handle:read("*a")
    handle:close()
    -- A tracked path that reads as nothing is a directory: git records a
    -- nested repository (a gitlink) or a symlink to a folder as one entry.
    -- Its contents are some other repository's, so it is left out.
    if text == nil then return nil end
    if text:sub(1, 8192):find("%z") then return nil end
    if category == "maybe_source" then
        if text:sub(1, 2) ~= "#!" then return nil end
        category = "source"
    end
    -- A document or note holding exported conversation turns is transcript
    -- material filed somewhere else (a README that swallowed a backup pack, a
    -- notes/conversations/ record). The transcript half measures conversations
    -- turn by turn; counting the file here too would count them twice.
    if (category == "docs" or category == "notes")
        and text:find("\n### User Request %d") and text:find("\n### Assistant Response %d") then
        return nil
    end
    if category == "source" and names_someone_else(text, repo_rules.header_lines) then
        category = "vendored"
    end
    return category, hash64(text), characters(text)
end
-- }}}

-- {{{ local function run_count_worker()
-- One worker's share of the repository: reads "pile<TAB>path" lines, writes
--   pile  content-hash  characters  path
local function run_count_worker(list_path, out_path)
    local out = assert(io.open(out_path, "wb"))
    for line in io.lines(list_path) do
        local category, path = line:match("^([%w_]+)\t(.+)$")
        local final, hash, size = count_file(category, path)
        if final then
            out:write(string.format("%s\t%s\t%d\t%s\n", final, hash, size, path))
        end
    end
    out:write(WORKER_FINISHED, "\n")
    out:close()
end
-- }}}

