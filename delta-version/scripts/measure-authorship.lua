-- {{{ local function with_commas()
local function with_commas(n)
    local grouped = tostring(n):reverse():gsub("(%d%d%d)", "%1,"):reverse()
    return (grouped:gsub("^,", ""))
end
-- }}}

-- {{{ local function render_terminal()
local function render_terminal(totals)
    local function row(label, value)
        print(string.format("  %-28s %14s characters", label, with_commas(value)))
    end
    print("The four figures:")
    row("human-written text", totals.human_written_total)
    row("machine-written text", totals.machine_written_total)
    row("source code in the tree", totals.source_characters)
    row("documents in the tree", totals.docs_characters)
    print("")
    print(string.format("From %d transcripts, %s distinct turns (%s copies seen):",
        totals.transcripts_counted, with_commas(totals.turns_counted),
        with_commas(totals.turn_copies_seen)))
    row("typed in conversation", totals.human_characters)
    row("written by the model", totals.machine_characters)
    print(string.format("  %-28s %14.2f", "machine per person (chat)", totals.ratio))
    row("set aside: pasted output", totals.excluded_paste_characters)
    row("set aside: tool-generated", totals.system_characters)
    print("")
    print(string.format("From %s tracked files (%s duplicate copies counted once):",
        with_commas(totals.repo_files_counted), with_commas(totals.repo_duplicate_files)))
    row("notes (the person's)", totals.notes_characters)
    row("set aside: vendored", totals.vendored_characters)
end
-- }}}

-- {{{ local function render_largest()
-- The biggest files in each pile, for checking that the rules put things
-- where they belong.
local function render_largest(kept_files, how_many)
    local piles = { "notes", "docs", "source", "vendored" }
    for _, pile in ipairs(piles) do
        local members = {}
        for _, file in ipairs(kept_files) do
            if file.pile == pile then members[#members + 1] = file end
        end
        table.sort(members, function(a, b) return a.size > b.size end)
        print(pile .. ":")
        for index = 1, math.min(how_many, #members) do
            print(string.format("  %12s  %s", with_commas(members[index].size), members[index].path))
        end
    end
end
-- }}}

-- {{{ local function render_json()
local function render_json(totals)
    local fields = { "human_written_total", "machine_written_total",
                     "source_characters", "docs_characters", "notes_characters",
                     "human_characters", "machine_units", "machine_unit_name", "ratio",
                     "transcripts_counted", "excluded_paste_characters",
                     "system_characters", "turns_counted", "turn_copies_seen",
                     "vendored_characters", "repo_files_counted", "repo_duplicate_files" }
    print("{")
    for index, field in ipairs(fields) do
        local value = totals[field]
        local shown = type(value) == "string" and string.format("%q", value)
            or (field == "ratio" and string.format("%.4f", value) or tostring(value))
        print(string.format('  "%s": %s%s', field, shown, index < #fields and "," or ""))
    end
    print("}")
end
-- }}}

