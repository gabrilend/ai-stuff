-- {{{ local function transcript_files()
-- Every markdown file in any llm-transcripts/ folder, skipping git's own
-- store, the transcript keepers' .patches/ records, and .bak copies.
local function transcript_files()
    return read_command(string.format(
        "find %q -path '*/.git' -prune -o -path '*/.patches' -prune -o " ..
        "-path '*/llm-transcripts/*' -type f -name '*.md' -print | sort", DIR))
end
-- }}}

-- {{{ local function scratch_directory()
-- A fresh folder in the RAM tier for this run's worker lists and outputs.
-- The shared library rebuilds the tier first, since a reboot empties RAM.
local function scratch_directory()
    local ensured = os.execute(string.format(
        "bash -c 'source %q && ensure_ram_tiers %q' >&2", RAM_TIER_LIBRARY, PROJECT_HOME))
    if ensured ~= 0 and ensured ~= true then
        error("could not prepare the RAM tier for " .. PROJECT_HOME, 0)
    end
    local base = PROJECT_HOME .. "/tmp/shared-memory/measure-authorship"
    os.execute(string.format("mkdir -p %q", base))
    return read_command(string.format("mktemp -d %q", base .. "/run.XXXXXX"))[1]
end
-- }}}

-- {{{ local function run_in_parallel()
-- Deals the work lines round-robin into one share per worker, starts every
-- worker at once in the background (the given worker mode: --worker for
-- transcripts, --count-worker for the repository's files), waits for all of
-- them, and returns their output paths. Processes, because LuaJIT has no
-- threads; round-robin, because the lines arrive sorted by path and a few
-- very large files sit together.
local function run_in_parallel(work, worker_mode)
    local count = WORKER_COUNT or tonumber(read_command("nproc")[1])
    if count < 1 then error("need at least one worker", 0) end
    if count > #work then count = math.max(1, #work) end

    local scratch = scratch_directory()
    local shares, outputs, commands = {}, {}, {}
    for index = 1, count do
        shares[index] = assert(io.open(string.format("%s/share-%d.list", scratch, index), "wb"))
        outputs[index] = string.format("%s/share-%d.records", scratch, index)
    end
    for index, line in ipairs(work) do
        shares[(index - 1) % count + 1]:write(line, "\n")
    end
    for index = 1, count do
        shares[index]:close()
        commands[index] = string.format("luajit %q %s --dir=%q %q %q &", SCRIPT_PATH,
            worker_mode, DIR, string.format("%s/share-%d.list", scratch, index), outputs[index])
    end
    local status = os.execute(table.concat(commands, " ") .. " wait")
    if status ~= 0 and status ~= true then error("a worker failed", 0) end
    for _, output in ipairs(outputs) do
        local handle = io.open(output, "rb")
        if not handle then error("a worker wrote nothing: " .. output, 0) end
        local text = handle:read("*a")
        handle:close()
        if text:sub(-#WORKER_FINISHED - 1) ~= WORKER_FINISHED .. "\n" then
            error("a worker stopped before finishing its share (" .. output .. ")", 0)
        end
    end
    return outputs, scratch
end
-- }}}

-- {{{ local function merge()
-- Folds every worker's records by key. The person's side of a turn is the
-- same in every copy, so the first copy's is kept; the machine's answer
-- differs between renderings at different levels of detail, so the longest
-- is kept. Returns the totals.
local function merge(outputs, files_seen)
    local turns = {}
    local instances = 0
    for _, output in ipairs(outputs) do
        for line in records_of(output) do
            local key, human, machine, pasted, system, answer =
                line:match("^(%x+)\t(%d+)\t(%d+)\t(%d+)\t(%d+)\t(%d+)$")
            if not key then error("malformed worker record: " .. line, 0) end
            instances = instances + 1
            local turn = turns[key]
            if not turn then
                turns[key] = { human = tonumber(human), machine = tonumber(machine),
                               pasted = tonumber(pasted), system = tonumber(system),
                               answer = tonumber(answer) }
            elseif tonumber(answer) > turn.answer then
                turn.answer = tonumber(answer)
            end
        end
    end

    local totals = { human_characters = 0, machine_characters = 0,
                     excluded_paste_characters = 0, system_characters = 0,
                     turns_counted = 0, turn_copies_seen = instances,
                     transcripts_counted = files_seen }
    for _, turn in pairs(turns) do
        totals.turns_counted = totals.turns_counted + 1
        totals.human_characters = totals.human_characters + turn.human
        totals.machine_characters = totals.machine_characters + turn.machine + turn.answer
        totals.excluded_paste_characters = totals.excluded_paste_characters + turn.pasted
        totals.system_characters = totals.system_characters + turn.system
    end
    totals.machine_units = totals.machine_characters
    totals.machine_unit_name = "characters"
    -- Machine characters per human character. With nothing typed there is no
    -- ratio to state; zero says "nothing measured" rather than dividing by it.
    totals.ratio = totals.human_characters > 0
        and totals.machine_characters / totals.human_characters or 0
    return totals
end
-- }}}

-- {{{ local function merge_files()
-- Folds the workers' file records into pile totals. A content hash seen more
-- than once is one file kept in several places: counted once, in the most
-- personal pile any copy landed in (notes, then docs, then source, then
-- vendored). Returns the totals and every kept file, for the largest listing.
local PILE_RANK = { notes = 1, docs = 2, source = 3, vendored = 4 }
local function merge_files(outputs)
    local by_hash = {}
    local copies = 0
    for _, output in ipairs(outputs) do
        for line in records_of(output) do
            local pile, hash, size, path = line:match("^(%a+)\t(%x+)\t(%d+)\t(.+)$")
            if not pile or not PILE_RANK[pile] then error("malformed file record: " .. line, 0) end
            local kept = by_hash[hash]
            if kept then
                copies = copies + 1
                -- keep the more personal pile; on a tie, the earlier path, so
                -- the answer does not depend on which worker finished first
                if PILE_RANK[pile] < PILE_RANK[kept.pile]
                    or (PILE_RANK[pile] == PILE_RANK[kept.pile] and path < kept.path) then
                    kept.pile, kept.path = pile, path
                end
            else
                by_hash[hash] = { pile = pile, size = tonumber(size), path = path }
            end
        end
    end

    local totals = { notes_characters = 0, docs_characters = 0, source_characters = 0,
                     vendored_characters = 0, repo_files_counted = 0,
                     repo_duplicate_files = copies }
    local kept_files = {}
    for _, file in pairs(by_hash) do
        totals[file.pile .. "_characters"] = totals[file.pile .. "_characters"] + file.size
        totals.repo_files_counted = totals.repo_files_counted + 1
        kept_files[#kept_files + 1] = file
    end
    return totals, kept_files
end
-- }}}

-- {{{ local function measure_repository()
-- The repository half: list what git tracks, decide each path's pile, count
-- the files in parallel, merge.
local function measure_repository()
    local files = tracked_files()
    if #files == 0 then error("git tracks no files under " .. DIR, 0) end
    local vendored = vendored_directories(files)
    local work = {}
    for _, path in ipairs(files) do
        local pile = classify_path(path, vendored)
        if pile then work[#work + 1] = pile .. "\t" .. path end
    end
    local outputs, scratch = run_in_parallel(work, "--count-worker")
    local totals, kept_files = merge_files(outputs)
    os.execute(string.format("rm -r %q", scratch))
    return totals, kept_files
end
-- }}}

-- {{{ local function measure()
-- Both halves, and the four headline figures built from them:
--   human_written_total   = the person's transcript characters + notes
--   machine_written_total = the model's transcript characters
--   source_characters, docs_characters = the repository's piles
local function measure()
    local files = transcript_files()
    if #files == 0 then error("no transcripts found under " .. DIR, 0) end
    local outputs, scratch = run_in_parallel(files, "--worker")
    local totals = merge(outputs, #files)
    os.execute(string.format("rm -r %q", scratch))

    local repository, kept_files = measure_repository()
    for field, value in pairs(repository) do totals[field] = value end
    totals.human_written_total = totals.human_characters + totals.notes_characters
    totals.machine_written_total = totals.machine_characters
    return totals, kept_files
end
-- }}}

