-- {{{ Utility Functions

-- {{{ local function read_command()
local function read_command(command)
    local pipe = io.popen(command)
    if not pipe then error("could not run: " .. command, 0) end
    local lines = {}
    for line in pipe:lines() do
        if line ~= "" then lines[#lines + 1] = line end
    end
    pipe:close()
    return lines
end
-- }}}

-- {{{ local function read_whole()
local function read_whole(path)
    local handle = io.open(path, "rb")
    if not handle then error("cannot read " .. path, 0) end
    local text = handle:read("*a")
    handle:close()
    return text
end
-- }}}

-- {{{ local function normalise()
-- One space for every run of whitespace, none at the ends. The exporter wraps
-- lines at its own width, and a wrap must not change what is counted or keyed.
local function normalise(text)
    return (text:gsub("%s+", " "):gsub("^ ", ""):gsub(" $", ""))
end
-- }}}

-- {{{ local function characters()
-- Characters in normalised text: UTF-8 code points, which is the byte count
-- less the continuation bytes (0x80-0xBF) that carry multi-byte characters.
local function characters(text)
    local normalised = normalise(text)
    local _, continuations = normalised:gsub("[\128-\191]", "")
    return #normalised - continuations
end
-- }}}

-- {{{ local function hash64()
-- A 64-bit key as sixteen hex digits: two 32-bit FNV-1a passes with different
-- starting values. Workers hand keys to the merger as hashes rather than whole
-- texts; at a few tens of thousands of turns, a 64-bit collision is not a
-- practical concern (a 32-bit one would be, at about one chance in a hundred).
local function hash64(text)
    local low, high = 0x811c9dc5, 0x050c5d1f
    for index = 1, #text do
        local byte = text:byte(index)
        low = bit.tobit(bit.bxor(low, byte) * 16777619)
        high = bit.tobit(bit.bxor(high, byte) * 16777619)
    end
    return bit.tohex(high) .. bit.tohex(low)
end
-- }}}

