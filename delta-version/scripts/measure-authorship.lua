-- {{{ Classifying a user turn

-- {{{ local function matches_any()
local function matches_any(text, patterns)
    for _, pattern in ipairs(patterns) do
        if text:find(pattern) then return true end
    end
    return false
end
-- }}}

-- {{{ local function is_log_line()
-- A line shaped like a log line or like pasted program output. Program-output
-- shapes are exact enough to decide alone; the log shapes include one loose
-- shape (a short capital word) that needs the level check below.
local function is_log_line(line)
    if matches_any(line, config.output_line_shapes) then return true end
    if not matches_any(line, config.log_line_shapes) then return false end
    -- The bracketed-level shape is loose (any short capital word); only real
    -- log levels count, so an ordinary shouted word in prose is not a log.
    local level = line:match("^%s*%[?(%u%u%u%u?%u?%u?%u?)%]?:? ")
    if level and not line:find("[%w_%-%./]+%.%a+:%d+:") and not line:find("^%s*%[?%d") then
        return config.log_line_levels[level] == true
    end
    return true
end
-- }}}

-- {{{ local function blocks_of()
-- A user turn as blocks: each fenced code block is one block, and so is each
-- run of lines between blank lines outside a fence.
local function blocks_of(text)
    local blocks, current, fenced = {}, {}, false
    local function close_block()
        if #current > 0 then blocks[#blocks + 1] = current end
        current = {}
    end
    for line in (text .. "\n"):gmatch("([^\n]*)\n") do
        if line:match("^%s*```") then
            if fenced then
                current[#current + 1] = line
                close_block()
                fenced = false
            else
                close_block()
                current[#current + 1] = line
                fenced = true
            end
        elseif not fenced and line:match("^%s*$") then
            close_block()
        else
            current[#current + 1] = line
        end
    end
    close_block()
    return blocks
end
-- }}}

-- {{{ local function is_pasted_log()
-- Two paths to "log": a strong signature anywhere in the block, or half or more
-- of its non-empty lines shaped like log lines. A block of prose that mentions
-- an error in passing fails both and stays the person's.
local function is_pasted_log(block)
    local lines, log_like = 0, 0
    for _, line in ipairs(block) do
        if not line:match("^%s*```") and not line:match("^%s*$") then
            if matches_any(line, config.strong_signatures) then return true end
            lines = lines + 1
            if is_log_line(line) then log_like = log_like + 1 end
        end
    end
    return lines > 0 and log_like * 2 >= lines
end
-- }}}

-- {{{ local function reads_as_prose()
-- Does a block contain a sentence? Three paths to yes:
--   it ends in a question mark ("Why?", "Any idea?") -- logs report, people ask
--   it holds six plain words in a row
--   something ends a sentence (". " or a final ".", "?", "!", ":") after a run
--   of at least three ordinary words
local function reads_as_prose(block)
    local text = normalise(table.concat(block, " "))
    if text:find("%a%?$") then return true end
    -- Six plain words in a row is someone talking, punctuated or not; a log
    -- line breaks its words with =, :, /, quotes or digits long before six.
    if text:find("%a+ %a+ %a+ %a+ %a+ %a+") then return true end
    if not text:find("%a+ %a+ %a+") then return false end
    return text:find("[%.%?!:] ") ~= nil or text:find("[%.%?!:]$") ~= nil
end
-- }}}

-- {{{ local function split_typed()
-- Human prose of a turn into typed characters and pasted-log characters.
--
-- The exporter re-wraps long lines and sets the pieces apart with blank lines,
-- so one pasted log line can arrive as several paragraphs whose later pieces
-- ("from", "runner.vram=...") look like nothing on their own. A log therefore
-- spreads to its neighbours, by two rules applied until nothing changes:
--   a block right after a log that is not a sentence -> log (a wrapped tail)
--   a short block (under 60 characters) between two  -> log (a label inside
--   log blocks                                          the dump, "The output
--                                                       was:", say)
-- A sentence outside a log's span stops the spread, so "the output looked like
-- this:" before a log, and the question after it, stay the person's; so does
-- a full paragraph between two quoted excerpts, which is the person replying.
-- The cost: a short remark between two pasted logs is set aside with them.
local function split_typed(text)
    local blocks = blocks_of(text)
    local is_log = {}
    for index, block in ipairs(blocks) do is_log[index] = is_pasted_log(block) end
    local changed = true
    while changed do
        changed = false
        for index = 2, #blocks do
            if not is_log[index] and is_log[index - 1] then
                -- Only a short label counts as inside a dump; a paragraph
                -- between two quoted excerpts is the person replying to them.
                local sandwiched = is_log[index + 1] == true
                    and characters(table.concat(blocks[index], " ")) < 60
                if sandwiched or not reads_as_prose(blocks[index]) then
                    is_log[index] = true
                    changed = true
                end
            end
        end
    end

    local typed, pasted = 0, 0
    for index, block in ipairs(blocks) do
        local size = characters(table.concat(block, "\n"))
        if is_log[index] then
            -- The person's lead-in sometimes shares the paragraph with the
            -- paste ("...available context space.time=2025-11-16..."). The
            -- lines before the first log-shaped line stay theirs when they
            -- read as a sentence; otherwise the whole block is the paste.
            local lead = {}
            for _, line in ipairs(block) do
                if is_log_line(line) or matches_any(line, config.strong_signatures) then break end
                lead[#lead + 1] = line
            end
            local kept = (#lead > 0 and #lead < #block and reads_as_prose(lead))
                and characters(table.concat(lead, "\n")) or 0
            typed = typed + kept
            pasted = pasted + size - kept
        else
            typed = typed + size
        end
    end
    return typed, pasted
end
-- }}}

-- {{{ local function classify_user_turn()
-- Returns the turn's characters as { human, machine, pasted, system }.
-- Who sat in the user's chair decides the first split (see ORIGINS below);
-- in a session the person typed into, the paths are, in order:
--   the model's own words        -> all machine (a compaction summary, a
--                                   message from another model session)
--   a tool-generated turn        -> all system
--   a wrapper around typed text  -> the typed part human (less pasted logs),
--                                   the rest system
--   anything else                -> human, less pasted logs
-- Any <system-reminder> spans are cut out first and counted as system.
local ORIGINS = {
    subagent = function(text, counts) counts.machine = characters(text); return true end,
    person   = function() return false end,
}
local function classify_user_turn(text, origin)
    local counts = { human = 0, machine = 0, pasted = 0, system = 0 }
    if ORIGINS[origin](text, counts) then return counts end

    local reminders = 0
    text = text:gsub("<system%-reminder>.-</system%-reminder>", function(span)
        reminders = reminders + characters(span)
        return " "
    end)
    counts.system = reminders

    local opening = normalise(text)
    if matches_any(opening, config.machine_openings) then
        counts.machine = characters(text)
        return counts
    end
    if matches_any(opening, config.system_openings) then
        counts.system = counts.system + characters(text)
        return counts
    end
    for _, wrapper in ipairs(config.typed_inside) do
        if opening:find(wrapper.whole) then
            local inside = text:match(wrapper.open .. "(.-)" .. wrapper.close) or ""
            local typed, pasted = split_typed(inside)
            counts.human, counts.pasted = typed, pasted
            counts.system = counts.system + characters(text) - characters(inside)
            return counts
        end
    end
    counts.human, counts.pasted = split_typed(text)
    return counts
end
-- }}}

-- }}}

-- Every worker's last line. The shell's `wait` reports success even when a
-- worker died part-way, so a missing last line is the only honest signal
-- that a share was not finished -- and an unfinished share would quietly
-- shrink every total.
local WORKER_FINISHED = "#finished"

-- {{{ local function records_of()
-- A worker's output, line by line, without its closing line.
local function records_of(output)
    local next_line = io.lines(output)
    return function()
        local line = next_line()
        if line == WORKER_FINISHED then return nil end
        return line
    end
end
-- }}}

-- {{{ Parsing transcripts (the worker's job)

-- {{{ local function parse_transcript()
-- Walks one transcript and calls emit(record) once per turn instance. A turn
-- instance is one user turn in one place in one file, with every assistant
-- response that follows it before the next user turn summed onto it (the
-- exporter splits long responses into "(continued)" parts across separators).
--
-- Each user turn is keyed by its own normalised text and the two user turns
-- before it in the same conversation. Every copy of a conversation, in any
-- file, at any level of detail, produces the same keys; the same "continue"
-- in two conversations does not. The key carries its origin's initial, so a
-- model-written prompt is never merged with a person's message.
local function parse_transcript(path, emit)
    local text = read_whole(path)
    local role, lines = nil, {}
    local origin = "person"
    local previous, before_previous = "", ""
    local instance = nil   -- the open turn instance, until the next user turn

    local function close_instance()
        if instance then emit(instance) end
        instance = nil
    end

    -- Two origins: a session id "agent-…" is a sub-agent wherever it is
    -- saved; every other session is the person's (see the note in the configuration on
    -- why an agent-named file is not evidence of a script).
    local function start_conversation(session_id)
        close_instance()
        origin = session_id:match("^agent%-") and "subagent" or "person"
        previous, before_previous = "", ""
    end

    -- {{{ local function flush()
    local function flush()
        local body = table.concat(lines, "\n")
        lines = {}
        if role == "user" then
            local normalised = normalise(body)
            -- An empty user turn is an export artifact, not a message; some
            -- renderings keep it and some drop it, so it stays out of the chain.
            if normalised == "" then return end
            close_instance()
            local key = hash64(origin:sub(1, 1) .. "\1" .. before_previous .. "\1" ..
                               previous .. "\1" .. normalised)
            before_previous, previous = previous, normalised
            local counts = classify_user_turn(body, origin)
            instance = { key = key, human = counts.human, machine = counts.machine,
                         pasted = counts.pasted, system = counts.system, answer = 0 }
        elseif role == "assistant" then
            local size = characters(body)
            if size == 0 then return end
            if not instance then
                -- A response with no user turn before it in this conversation
                -- (a continuation that opens a file): keyed by its own text.
                instance = { key = hash64("O\1" .. normalise(body)), human = 0,
                             machine = 0, pasted = 0, system = 0, answer = 0 }
            end
            instance.answer = instance.answer + size
        end
    end
    -- }}}

    for line in (text .. "\n"):gmatch("([^\n]*)\n") do
        local session = line:match("^# Conversation Summary:%s*(%S*)")
        if session then
            flush(); role = nil
            start_conversation(session)
        elseif line:match("^### User Request %d+") then
            flush(); role = "user"
        elseif line:match("^### Assistant Response %d+") then
            flush(); role = "assistant"
        elseif line == config.separator then
            flush(); role = nil
        elseif matches_any(line, config.boundaries) then
            -- A conversation heading ends the open turn even without a
            -- separator before it: the recursive exports (v1..v5) start each
            -- embedded conversation straight after the last response, and
            -- that response would otherwise swallow the next conversation.
            flush(); role = nil
            start_conversation("")
        elseif role then
            lines[#lines + 1] = line
        end
    end
    flush()
    close_instance()
end
-- }}}

-- {{{ local function run_worker()
-- One worker: reads its share of file paths, parses each, and writes one
-- tab-separated record per turn instance to its output file:
--   key  human  machine  pasted  system  answer
local function run_worker(list_path, out_path)
    local out = assert(io.open(out_path, "wb"))
    local function emit(record)
        out:write(string.format("%s\t%d\t%d\t%d\t%d\t%d\n", record.key, record.human,
            record.machine, record.pasted, record.system, record.answer))
    end
    for path in io.lines(list_path) do
        parse_transcript(path, emit)
    end
    out:write(WORKER_FINISHED, "\n")
    out:close()
end
-- }}}

