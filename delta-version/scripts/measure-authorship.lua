-- {{{ Entry
local function main()
    local mode = mode_arguments[1] or "--terminal"
    local modes = {
        ["--worker"] = function()
            run_worker(mode_arguments[2], mode_arguments[3])
        end,
        ["--count-worker"] = function()
            run_count_worker(mode_arguments[2], mode_arguments[3])
        end,
        ["--terminal"] = function() render_terminal((measure())) end,
        ["--json"] = function() render_json((measure())) end,
        ["--largest"] = function()
            local _, kept_files = measure_repository()
            render_largest(kept_files, tonumber(mode_arguments[2]) or 15)
        end,
    }
    local run = modes[mode]
    if not run then
        io.stderr:write("unknown mode: " .. mode .. "\nexpected --terminal or --json\n")
        os.exit(2)
    end
    run()
end

local ok, failure = xpcall(main, function(message)
    if type(message) == "string" and not message:match("^[^\n]*:%d+:") then
        return message
    end
    return debug.traceback(message, 2)
end)
if not ok then
    io.stderr:write("measure-authorship: " .. tostring(failure) .. "\n")
    os.exit(1)
end
