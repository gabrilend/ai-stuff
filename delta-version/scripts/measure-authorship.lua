#!/usr/bin/env luajit
-- measure-authorship.lua - How much of this repository's conversation did the
-- person write, and how much did the machine?
--
-- In plain terms: every conversation that built the repository is saved as a
-- transcript. This reads all of them, counts the characters the person typed
-- and the characters the model wrote, and reports the two totals and their
-- ratio. Pasted material counts as the person's (pasting something means you
-- read it and chose it), except a pasted error or log, which was the machine's
-- output being handed back. Messages the tool generated on its own -- warm-ups,
-- command output, notifications -- belong to neither side and are reported
-- apart, so every rule can be checked rather than trusted.
--
-- The same conversation is often saved in several places (two projects' folders,
-- a day file and a date-range file, one early conversation at five levels of
-- detail), so turns are matched by their content and counted once.
--
-- The unit is characters on both sides: the transcripts record no token counts,
-- and characters counted the same way on both sides keep the ratio honest.
--
-- It then reads the repository's own tracked files and sorts them into piles:
-- notes (hand-written, so they join the person's side), source code, and
-- documents (issue files included), leaving out generated copies, inputs and
-- outputs, and setting aside code that belongs to someone else. The four
-- headline figures are: human-written text, machine-written text, source code
-- in the tree, documents in the tree.
--
-- Usage:
--   measure-authorship.lua                 -- terminal summary
--   measure-authorship.lua --json          -- machine-readable
--   measure-authorship.lua --largest [N]   -- the N biggest files in each pile
--   measure-authorship.lua --dir=/path     -- measure another checkout (any position)
--   measure-authorship.lua --workers=N     -- how many parallel workers (default: CPU count)
--   measure-authorship.lua --worker LIST OUT        -- internal: transcripts share
--   measure-authorship.lua --count-worker LIST OUT  -- internal: repository share
--
-- See measure-authorship.info.md for the counting rules as a table, and
-- delta-version/issues/059-measure-human-and-machine-authorship.md for why.

